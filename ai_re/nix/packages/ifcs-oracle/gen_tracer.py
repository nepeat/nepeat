"""Generate the libifcs call tracer wrappers (C) for one IFCS ABI.

  gen_tracer.py --header build/gen/ifcs_api.h -o trace_ours.c
      every entry point of our ifcs_api.h (IFCS 0.12.41, the box's libifcs.so;
      generated by tools/gen_ifcs_api.py from src/ifcs_api.h.in):
      typed wrappers, bound to the real library by ifcs_trace_bind().
  gen_tracer.py --ctypes <isai>/share/isai/pyctypes/ifcs_ctypes.py \
                --imports imports.txt --abi isai-6.2.0 -o trace_isai.c
      every ifcs_* function libsai imports (isai 6.2.0, IFCS 0.16.2, amd64):
      generic integer-register wrappers resolved with RTLD_NEXT (LD_PRELOAD).
      Argument kinds and the attribute layout (size, value/bitmap offsets,
      union members in bitmap order) come from the ctypes file, evaluated
      with its library loader stubbed. Functions with float or by-value
      struct arguments, or variadic ones, are not wrapped (left to the real
      library, untraced).
Only names, types and layouts are taken from the vendor file, at build time;
the output is a build product (never committed).
"""
import argparse, re, sys

ARG_KINDS = ["TRA_U", "TRA_I", "TRA_U64", "TRA_HANDLE", "TRA_PTR", "TRA_FN", "TRA_STR", "TRA_ATTRS", "TRA_PU",
             "TRA_PI", "TRA_PU64", "TRA_PHANDLE", "TRA_STRUCT"]
COUNTED = {"TRA_ATTRS", "TRA_PU", "TRA_PI", "TRA_PU64", "TRA_PHANDLE"}


def counts(kinds):
    """Index of the count argument of each array-ish pointer, or -1 (single).
    Count = the nearest preceding plain integer that is not argument 0 (the
    node id), skipping pointers in between; the last argument, when an
    integer pointer, is an out-count (single)."""
    out = []
    for i, k in enumerate(kinds):
        c = -1
        if k in COUNTED and not (i == len(kinds) - 1 and k in ("TRA_PU", "TRA_PI")):
            j = i - 1
            while j >= 1:
                if kinds[j] in ("TRA_U", "TRA_I"):
                    c = j
                    break
                if kinds[j] in ("TRA_HANDLE", "TRA_U64", "TRA_STR", "TRA_FN"):
                    break
                j -= 1
        out.append(c)
    return out


def emit_args(kinds, cnt, sizes, names):
    s = []
    for i, k in enumerate(kinds):
        c = "(uint64_t)%s" % names[cnt[i]] if cnt[i] >= 0 else "TR_SINGLE"
        v = names[i]
        if k == "TRA_STRUCT" and sizes[i] and sizes[i].startswith("&"):
            v, size = sizes[i], "sizeof(%s)" % names[i]
            s.append("        tr_arg(l, TRA_STRUCT, (uint64_t)(uintptr_t)%s, 0, (uint32_t)%s);" % (v, size))
            continue
        cast = "(uint64_t)(uintptr_t)" if "*" in (sizes[i] or "") or k in ("TRA_PTR", "TRA_FN", "TRA_STR", "TRA_ATTRS", "TRA_PU", "TRA_PI", "TRA_PU64", "TRA_PHANDLE", "TRA_STRUCT") else "(uint64_t)"
        size = sizes[i] if (k == "TRA_STRUCT") else "0"
        s.append("        tr_arg(l, %s, %s%s, %s, (uint32_t)%s);" % (k, cast, v, c, size))
    return "\n".join(s)


# ---------------------------------------------------------------- our header
def from_header(path):
    txt = open(path).read()
    # area headers ifcs_api.h includes (ifcs_api_<area>.h) declare more entry points
    import os
    for inc in re.findall(r'^#include "(ifcs_api_\w+\.h)"', txt, re.M):
        txt += "\n" + open(os.path.join(os.path.dirname(path), inc)).read()
    fns = []
    for m in re.finditer(r"IFCS_FN\(\s*([^,]+?)\s*,\s*(\w+)\s*,\s*\((.*?)\)\)\s*$", txt, re.M | re.S):
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
        types = [strip_name(a) for a in args.split(",")] if args.strip() else []
        fns.append((ret, name, types))
    return fns


def strip_name(a):
    """'const char* cfg' -> 'const char*', 'uint32_t* n' -> 'uint32_t*', 'int' -> 'int'."""
    t = re.sub(r"\s*\*\s*", "* ", a.strip()).strip()
    toks = t.split()
    if len(toks) >= 2 and re.match(r"^[A-Za-z_]\w*$", toks[-1]) and toks[-2] not in ("const", "unsigned", "struct", "signed"):
        toks = toks[:-1]
    return " ".join(toks).replace("* ", "*").replace(" *", "*")


def header_kind(t):
    t = re.sub(r"\s+", " ", t).replace(" *", "*")
    if t == "ifcs_attr_t*": return "TRA_ATTRS", None
    if t == "ifcs_handle_t*": return "TRA_PHANDLE", None
    if t == "ifcs_handle_t": return "TRA_HANDLE", None
    if t in ("uint32_t*",): return "TRA_PU", None
    if t in ("int*",): return "TRA_PI", None
    if t == "uint64_t*": return "TRA_PU64", None
    if t == "const char*": return "TRA_STR", None
    if t == "void*": return "TRA_PTR", None
    if t.endswith("_fn_t") or t in ("ifcs_log_notify_t", "ifcs_l2_entry_user_cb_t"): return "TRA_FN", None
    if t in ("ifcs_node_id_t", "uint32_t", "ifcs_devport_t", "ifcs_attr_id_t"): return "TRA_U", None
    if t in ("int", "ifcs_bool_t", "ifcs_status_t"): return "TRA_I", None
    if t.endswith("*"): return "TRA_STRUCT", "sizeof(*%s)"
    return "TRA_STRUCT", "&%s"   # by value


def gen_header(path, abi):
    fns = from_header(path)
    o = ["/* generated by gen_tracer.py --header %s: do not edit */" % path.split("/")[-1],
         "#include \"ifcs_api.h\"", "#include \"trace_rt.h\"", "",
         "const struct tr_abi tr_abi = {\"%s\", sizeof(ifcs_attr_t), offsetof(ifcs_attr_t, value), "
         "sizeof(ifcs_attr_value_t), offsetof(ifcs_attr_t, bitmap), 8, 0, 0};" % abi, ""]
    for ret, name, types in fns:
        names = ["a%d" % i for i in range(len(types))]
        kinds, sizes = [], []
        for i, t in enumerate(types):
            k, sz = header_kind(t)
            kinds.append(k)
            sizes.append(sz % names[i] if sz else None)
        cnt = counts(kinds)
        params = ", ".join("%s %s" % (t, n) for t, n in zip(types, names)) or "void"
        rk = "TRR_STATUS" if ret == "ifcs_status_t" else "TRR_PTR" if ret.endswith("*") else "TRR_INT"
        o.append("%s %s(%s)\n{\n    static %s_fn real;\n    if (!real) real = (%s_fn)tr_resolve(\"%s\");" % (ret, name, params, name, name, name))
        o.append("    int top = tr_enter();\n    uint64_t t0 = top ? tr_now_us() : 0;")
        o.append("    %s r = real(%s);" % (ret, ", ".join(names)))
        o.append("    if (top) {\n        tr_line* l = tr_begin(\"%s\");" % name)
        if types: o.append(emit_args(kinds, cnt, sizes, names))
        o.append("        tr_end(l, %s, (uint64_t)(uintptr_t)r, tr_now_us() - t0);\n    }\n    tr_leave();\n    return r;\n}\n" % rk)
    return "\n".join(o)


# ---------------------------------------------------------------- ctypes file
def load_ctypes(path):
    import ctypes
    src = open(path).read()
    stub = "class _TrStub:\n    def has(self, *a): return False\n    def get(self, *a): raise KeyError(a)\n"
    src = re.sub(r'^(_libs\[[^\]]+\]) = load_library\([^)]*\)', r'\1 = _TrStub()', src, flags=re.M)
    src = src.replace("_libs = {}", "_libs = {}\n" + stub, 1)
    g = {"__name__": "ifcs_ctypes_tracer"}
    exec(compile(src, path, "exec"), g)
    sigs = {}
    for m in re.finditer(r"^\s+(\w+)\.argtypes = \[(.*)\]\s*$", src, re.M):
        sigs[m.group(1)] = [a.strip() for a in split_top(m.group(2))]
    rets = {m.group(1): m.group(2).strip() for m in re.finditer(r"^\s+(\w+)\.restype = (.*)$", src, re.M)}
    variadic = set(re.findall(r"(\w+) = _variadic_function\(", src))
    return g, sigs, rets, variadic


def split_top(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(": depth += 1
        if ch == ")": depth -= 1
        if ch == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip(): out.append(cur)
    return out


def ctypes_kind(g, t):
    import ctypes
    tt = t.replace(" ", "")
    if tt == "POINTER(ifcs_attr_t)": return "TRA_ATTRS", None
    if tt == "POINTER(ifcs_handle_t)": return "TRA_PHANDLE", None
    if tt == "ifcs_handle_t": return "TRA_HANDLE", None
    if tt in ("String", "c_char_p", "POINTER(c_char)"): return "TRA_STR", None
    if tt in ("POINTER(None)", "c_void_p"): return "TRA_PTR", None
    try:
        o = eval(t, g)
    except Exception:
        return None, None
    if isinstance(o, type) and issubclass(o, ctypes._CFuncPtr): return "TRA_FN", None
    if isinstance(o, type) and issubclass(o, ctypes._Pointer):
        tgt = o._type_
        if isinstance(tgt, type) and issubclass(tgt, ctypes._CFuncPtr): return "TRA_FN", None
        if isinstance(tgt, type) and issubclass(tgt, (ctypes.Structure, ctypes.Union)):
            return "TRA_STRUCT", str(ctypes.sizeof(tgt))
        if tgt in (ctypes.c_uint64, ctypes.c_int64, ctypes.c_ulonglong, ctypes.c_longlong) or ctypes.sizeof(tgt) == 8:
            return "TRA_PU64", None
        if tgt in (ctypes.c_float, ctypes.c_double): return "TRA_STRUCT", str(ctypes.sizeof(tgt))
        if ctypes.sizeof(tgt) == 4:
            return ("TRA_PI" if tgt in (ctypes.c_int, ctypes.c_int32, ctypes.c_long) else "TRA_PU"), None
        if isinstance(tgt, type) and issubclass(tgt, ctypes.Array): return "TRA_STRUCT", str(ctypes.sizeof(tgt))
        return "TRA_STRUCT", str(ctypes.sizeof(tgt))
    if o in (ctypes.c_float, ctypes.c_double): return None, None
    if isinstance(o, type) and issubclass(o, (ctypes.Structure, ctypes.Union, ctypes.Array)): return None, None
    if isinstance(o, type) and issubclass(o, ctypes._SimpleCData):
        if ctypes.sizeof(o) == 8: return "TRA_U64", None
        signed = o in (ctypes.c_int, ctypes.c_int8, ctypes.c_int16, ctypes.c_int32, ctypes.c_long, ctypes.c_short, ctypes.c_byte)
        return ("TRA_I" if signed else "TRA_U"), None
    return None, None


def members(g):
    import ctypes
    U = g["ifcs_attr_value_t"]
    out = []
    for name, typ in U._fields_:
        size = ctypes.sizeof(typ)
        kind, elem = "TRK_RAW", 0
        if name == "handle": kind = "TRK_HANDLE"
        elif name == "mac": kind = "TRK_MAC"
        elif typ in (ctypes.c_float,): kind = "TRK_FLT"
        elif isinstance(typ, type) and issubclass(typ, ctypes._SimpleCData):
            signed = typ in (ctypes.c_int, ctypes.c_int8, ctypes.c_int16, ctypes.c_int32, ctypes.c_int64, ctypes.c_long, ctypes.c_byte, ctypes.c_short)
            kind = "TRK_I" if signed else "TRK_U"
        elif isinstance(typ, type) and issubclass(typ, ctypes.Structure):
            f = {x[0]: x[1] for x in typ._fields_}
            arr = f.get("arr") or f.get("list")
            if "count" in f and arr is not None and issubclass(arr, ctypes._Pointer):
                kind = "TRK_HLIST" if name == "handle_list" else "TRK_LIST"
                try: elem = ctypes.sizeof(arr._type_)
                except Exception: elem = 1
        out.append((name, kind, min(size, 255), min(elem, 255)))
    return out


def gen_ctypes(path, imports, abi):
    import ctypes
    g, sigs, rets, variadic = load_ctypes(path)
    A = g["ifcs_attr_t"]
    fields = {f[0]: f for f in A._fields_}
    bm = getattr(A, "bitmap")
    mem = members(g)
    want = [l.strip() for l in open(imports) if l.strip()] if imports else sorted(sigs)
    o = ["/* generated by gen_tracer.py --ctypes (%s): do not edit */" % abi,
         "#include \"trace_rt.h\"", "", "static const struct tr_member members[] = {"]
    for n, k, sz, el in mem:
        o.append("    {\"%s\", %s, %d, %d}," % (n, k, sz, el))
    o.append("};")
    o.append("const struct tr_abi tr_abi = {\"%s\", %d, %d, %d, %d, %d, members, %d};" % (
        abi, ctypes.sizeof(A), A.value.offset, ctypes.sizeof(fields["value"][1]), bm.offset,
        ctypes.sizeof(fields["bitmap"][1]), len(mem)))
    o.append("")
    skipped = []
    nwrap = 0
    for name in want:
        if not name.startswith("ifcs_") or name not in sigs or name in variadic or name.startswith("ifcs_trace_"):
            skipped.append(name); continue
        types = sigs[name]
        kinds, sizes, ok = [], [], True
        for t in types:
            k, sz = ctypes_kind(g, t)
            if k is None: ok = False; break
            kinds.append(k); sizes.append(sz)
        rt = rets.get(name, "ifcs_status_t").replace(" ", "")
        if rt in ("c_float", "c_double", "ifcs_flt_t", "ifcs_dbl_t"): ok = False
        if rt not in ("ifcs_status_t", "None", "String", "c_char_p", "POINTER(None)", "c_void_p") and ok:
            try:
                ro = eval(rets.get(name), g)
                if isinstance(ro, type) and issubclass(ro, (ctypes.Structure, ctypes.Union)): ok = False
                if ro in (ctypes.c_float, ctypes.c_double): ok = False
            except Exception:
                ok = False
        if not ok or len(types) > 12:
            skipped.append(name); continue
        rk = ("TRR_STATUS" if rt == "ifcs_status_t" else "TRR_VOID" if rt == "None"
              else "TRR_PTR" if rt in ("String", "c_char_p", "POINTER(None)", "c_void_p") or rt.startswith("POINTER(") else "TRR_INT")
        names = ["a%d" % i for i in range(len(types))]
        cnt = counts(kinds)
        proto = ", ".join("uint64_t " + n for n in names) or "void"
        ptype = "uint64_t (*)(%s)" % (", ".join("uint64_t" for _ in names) or "void")
        o.append("uint64_t %s(%s)\n{\n    static void* real;\n    if (!real) real = tr_resolve(\"%s\");" % (name, proto, name))
        o.append("    int top = tr_enter();\n    uint64_t t0 = top ? tr_now_us() : 0;")
        o.append("    uint64_t r = ((%s)real)(%s);" % (ptype, ", ".join(names)))
        o.append("    if (top) {\n        tr_line* l = tr_begin(\"%s\");" % name)
        if types: o.append(emit_args(kinds, cnt, [s if k == "TRA_STRUCT" else None for k, s in zip(kinds, sizes)], names))
        o.append("        tr_end(l, %s, r, tr_now_us() - t0);\n    }\n    tr_leave();\n    return r;\n}\n" % rk)
        nwrap += 1
    o.append("/* %d wrapped; not wrapped (untraced): %d */" % (nwrap, len(skipped)))
    for s in skipped:
        o.append("/*   %s */" % s)
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header")
    ap.add_argument("--ctypes")
    ap.add_argument("--imports")
    ap.add_argument("--abi", default="ifcs-0.12.41-ours")
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    if a.header: out = gen_header(a.header, a.abi)
    elif a.ctypes: out = gen_ctypes(a.ctypes, a.imports, a.abi)
    else: ap.error("--header or --ctypes")
    open(a.o, "w").write(out + "\n")


if __name__ == "__main__":
    main()
