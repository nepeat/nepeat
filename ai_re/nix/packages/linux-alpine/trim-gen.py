#!/usr/bin/env python3
"""Regenerate trim.nix: modules in driver families that have no menu switch.

Reads a kernel .config (the "trimmed" variant's, after the menu-level cuts in
default.nix), and lists every =m symbol in FAMILIES that isn't in KEEP. Those
get forced to `no`. Rerun after a kernel version bump:

  nix build --no-link --print-out-paths \
    path:./nix#nixosConfigurations.dmc12.config.boot.kernelPackages.kernel.configfile
  python3 nix/packages/linux-alpine/trim-gen.py <that path> <unpacked kernel source> \
    > nix/packages/linux-alpine/trim.nix

Only modules (=m) are touched, and never a symbol that any Kconfig `select`
points at: nixpkgs' generate-config answers in menu order, and forcing `n` on a
symbol an earlier answer selected makes it re-ask until it dies ("repeated
question", hit with INPUT_FF_MEMLESS on 2026-11-15). Those fall away by
themselves once their selectors are off.
"""
import pathlib
import re
import sys

# Symbol prefixes: driver families without a menu-level switch.
FAMILIES = ["SENSORS_", "RTC_DRV_", "MFD_", "GPIO_", "I2C_", "SPI_", "SATA_", "PATA_",
            "MTD_", "REGULATOR_", "CHARGER_", "BATTERY_", "CRYPTO_DEV_", "HID_",
            "KEYBOARD_", "MOUSE_", "LEDS_", "BACKLIGHT_", "PWM_", "PINCTRL_", "COMMON_CLK_",
            "PHY_", "EXTCON_", "IIO_", "NVMEM_", "MISC_", "TOUCHSCREEN_", "INPUT_",
            "W1_", "VIRTIO_", "USB_G_", "USB_F_", "BACKLIGHT_", "STM_"]

# Needed by an Alpine board in ai_re (DMC-12 today; CS8210 when it joins), or
# by NixOS. Keep anything boot- or board-relevant here even if it is =y now.
KEEP = {
    "SENSORS_LM75", "SENSORS_INA2XX", "SENSORS_LM90", "SENSORS_TMP102",
    "RTC_DRV_DS1307",
    "GPIO_PL061", "GPIO_CDEV", "GPIO_SYSFS", "GPIO_PCA953X",
    "I2C_DESIGNWARE_CORE", "I2C_DESIGNWARE_PLATFORM", "I2C_MUX", "I2C_MUX_PCA954x",
    "I2C_MUX_GPIO", "I2C_CHARDEV", "I2C_SMBUS", "I2C_ALGOBIT",
    "SPI_DESIGNWARE", "SPI_DW_MMIO", "SPI_SPIDEV", "SPI_MUX",
    "SATA_AHCI", "SATA_AHCI_PLATFORM", "SATA_PMP",
    "MTD_SPI_NOR", "MTD_BLOCK", "MTD_OF_PARTS",
    "NVMEM_SYSFS", "MISC_FILESYSTEMS",
    "INPUT_EVDEV",
}


def select_targets(src):
    targets = set()
    for kc in pathlib.Path(src).rglob("Kconfig*"):
        for line in kc.read_text(errors="replace").splitlines():
            m = re.match(r"\s*(?:select|imply)\s+([A-Z0-9_]+)", line)
            if m:
                targets.add(m.group(1))
    return targets


def main(path, src):
    selected = select_targets(src)
    disable = []
    for line in open(path):
        m = re.match(r"CONFIG_([A-Za-z0-9_]+)=m$", line.strip())
        if not m:
            continue
        sym = m.group(1)
        if sym in KEEP or sym in selected or not any(sym.startswith(f) for f in FAMILIES):
            continue
        disable.append(sym)
    print("# Generated by trim-gen.py from the trimmed 7.x config; do not edit by hand.")
    print(f"# {len(disable)} modules in driver families with no menu switch (see trim-gen.py).")
    print("[")
    for i in range(0, len(disable), 4):
        print("  " + " ".join(f'"{s}"' for s in disable[i:i + 4]))
    print("]")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
