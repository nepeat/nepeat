#!/usr/bin/env python3
"""Generate the by-value struct part of the ABI conformance module.

One spec (STRUCTS) -> abi_gen.h (C types), abi_gen_c.c (C side, built by GCC)
and abi_gen.rs (Rust side, built by rustc). For every struct S and every
placement k (k u64 arguments before it: 0 = first in registers, 7 = straddles
the last argument register and the stack, 8 = wholly on the stack):

  Rust -> C    abi_c_arg_S_k(p0..pk-1, s, tail) returns a hash of what C got;
               Rust compares it with the hash of what it passed
  C -> Rust    abi_rs_arg_S_k, the same the other way (abi_c_check_rust)
  returns      abi_c_ret_S / abi_rs_ret_S build S from a seed; the caller
               compares every field with its own S from the same seed
  pointers     C calls a Rust function pointer (abi_c_cb_S), Rust calls a C
               function pointer (abi_c_fnp_S)
  layout       sizeof/alignof/offsetof of every test struct as GCC sees it,
               compared with Rust's (abi_c_layout)

Values are distinct per field and element (splitmix64 of seed, field,
element), so a field read from the wrong place, a wrong extension or a
wrong half shows up as a hash or field mismatch.
"""
import sys
from pathlib import Path

# (name, kind, attrs, [(field, type, count)])  type: u8..u64 s8..s64 bool u128 ptr
STRUCTS = [
    ("S1", "struct", "", [("a", "u8", 1)]),
    ("S2", "struct", "", [("a", "u16", 1)]),
    ("S3", "struct", "", [("a", "u8", 3)]),
    ("S4", "struct", "", [("a", "u32", 1)]),
    ("S5", "struct", "", [("a", "u8", 5)]),
    ("S6", "struct", "", [("a", "u16", 3)]),
    ("S7", "struct", "", [("a", "u8", 7)]),
    ("S8", "struct", "", [("a", "u64", 1)]),
    ("SM8", "struct", "", [("a", "u8", 1), ("b", "u16", 1), ("c", "u32", 1)]),
    ("SB3", "struct", "", [("a", "bool", 1), ("b", "bool", 1), ("c", "bool", 1)]),
    ("S9P", "struct", "packed", [("a", "u8", 1), ("b", "u64", 1)]),
    ("S12", "struct", "", [("a", "u32", 3)]),
    ("SI16", "struct", "", [("a", "s8", 1), ("b", "s16", 1), ("c", "s32", 1), ("d", "s64", 1)]),
    ("S16", "struct", "", [("a", "u64", 2)]),
    ("SM16", "struct", "", [("a", "u32", 1), ("b", "u64", 1)]),
    ("SP16", "struct", "", [("p", "ptr", 1), ("b", "bool", 1), ("x", "u32", 1)]),
    ("SA16", "struct", "aligned16", [("a", "u64", 1)]),
    ("SQ", "struct", "", [("q", "u128", 1)]),
    ("U12", "union", "", [("b", "u8", 12), ("a", "u64", 1)]),   # first field is the one set/hashed
    ("S17", "struct", "", [("a", "u8", 17)]),
    ("S24", "struct", "", [("a", "u64", 3)]),
    ("SM24", "struct", "", [("a", "u8", 1), ("b", "u64", 1), ("c", "u16", 1)]),
    ("S32", "struct", "", [("a", "u64", 4)]),
    ("SQM", "struct", "", [("a", "u8", 1), ("q", "u128", 1), ("c", "u16", 1)]),
]
PLACEMENTS = [0, 7, 8]

CT = {"u8": "u8", "u16": "u16", "u32": "u32", "u64": "u64", "s8": "s8", "s16": "s16",
      "s32": "s32", "s64": "s64", "bool": "bool", "u128": "u128", "ptr": "const void *"}
RT = {"u8": "u8", "u16": "u16", "u32": "u32", "u64": "u64", "s8": "i8", "s16": "i16",
      "s32": "i32", "s64": "i64", "bool": "bool", "u128": "u128", "ptr": "*const u8"}


def seed_of(si, k):
    return 0x1000 * (si + 1) + k


def c_types(out):
    w = out.append
    w("/* generated by gen_abi.py: do not edit */")
    w("#ifndef ABI_GEN_H\n#define ABI_GEN_H\n#include <linux/types.h>")
    for name, kind, attrs, fields in STRUCTS:
        a = {"packed": " __packed", "aligned16": " __aligned(16)", "": ""}[attrs]
        w(f"{kind} {name} {{")
        for f, t, n in fields:
            w(f"\t{CT[t]} {f}{'' if n == 1 else f'[{n}]'};")
        w(f"}}{a};")
    w("#endif")


def c_val(t, expr):
    if t == "bool":
        return f"(({expr}) & 1)"
    if t == "u128":
        return f"(((u128)({expr}) << 64) | abi_sm({expr}))"
    if t == "ptr":
        return f"((const void *)(uintptr_t)({expr}))"
    return f"(({CT[t]})({expr}))"


def c_mix(t, expr):
    if t == "u128":
        return [f"h = abi_mix(h, (u64)({expr} >> 64));", f"h = abi_mix(h, (u64){expr});"]
    if t == "ptr":
        return [f"h = abi_mix(h, (u64)(uintptr_t){expr});"]
    if t.startswith("s"):
        return [f"h = abi_mix(h, (u64)(s64){expr});"]
    return [f"h = abi_mix(h, (u64){expr});"]


def elems(fields, kind):
    fs = fields[:1] if kind == "union" else fields
    for fi, (f, t, n) in enumerate(fs):
        for j in range(n):
            yield fi, f, t, n, j


def key(fi, j):
    return f"0x{(fi * 0x9E37 + j * 0x85EB + 1):x}"


def c_side(out):
    w = out.append
    w("/* generated by gen_abi.py: do not edit */")
    w('#include <linux/kernel.h>\n#include <linux/printk.h>\n#include "abi_common.h"\n#include "abi_gen.h"')
    for si, (name, kind, attrs, fields) in enumerate(STRUCTS):
        # make, hash, equal
        w(f"static {kind} {name} make_{name}(u64 seed)\n{{\n\t{kind} {name} s;\n\tmemset(&s, 0, sizeof(s));")
        for fi, f, t, n, j in elems(fields, kind):
            lhs = f"s.{f}" + ("" if n == 1 else f"[{j}]")
            w(f"\t{lhs} = {c_val(t, f'abi_sm(seed ^ {key(fi, j)})')};")
        w("\treturn s;\n}")
        w(f"static u64 hash_{name}(u64 h, const {kind} {name} *s)\n{{")
        for fi, f, t, n, j in elems(fields, kind):
            ex = f"s->{f}" + ("" if n == 1 else f"[{j}]")
            for line in c_mix(t, ex):
                w("\t" + line)
        w("\treturn h;\n}")
        for k in PLACEMENTS:
            params = "".join(f"u64 p{i}, " for i in range(k))
            w(f"u64 abi_c_arg_{name}_{k}({params}{kind} {name} s, u64 tail);")
            w(f"u64 abi_c_arg_{name}_{k}({params}{kind} {name} s, u64 tail)\n{{\n\tu64 h = ABI_H0;")
            for i in range(k):
                w(f"\th = abi_mix(h, p{i});")
            w(f"\th = hash_{name}(h, &s);\n\treturn abi_mix(h, tail);\n}}")
            w(f"u64 abi_rs_arg_{name}_{k}({params}{kind} {name} s, u64 tail);")
        w(f"{kind} {name} abi_c_ret_{name}(u64 seed);")
        w(f"{kind} {name} abi_c_ret_{name}(u64 seed) {{ return make_{name}(seed); }}")
        w(f"{kind} {name} abi_rs_ret_{name}(u64 seed);")
        w(f"u64 abi_c_cb_{name}(u64 (*cb)({kind} {name}, u64), u64 seed);")
        w(f"u64 abi_c_cb_{name}(u64 (*cb)({kind} {name}, u64), u64 seed) {{ return cb(make_{name}(seed), abi_sm(seed + 999)); }}")
        w(f"void *abi_c_fnp_{name}(void);")
        w(f"void *abi_c_fnp_{name}(void) {{ return (void *)abi_c_arg_{name}_0; }}")
    # C checks Rust
    w("int abi_c_check_rust_structs(void);")
    w("int abi_c_check_rust_structs(void)\n{\n\tint fails = 0, i;\n\tu64 got, want, h;")
    for si, (name, kind, attrs, fields) in enumerate(STRUCTS):
        for k in PLACEMENTS:
            seed = seed_of(si, k)
            w("\t{")
            w(f"\t\t{kind} {name} s = make_{name}({seed});")
            args = "".join(f"abi_sm({seed} + 100 + {i}), " for i in range(k))
            w(f"\t\th = ABI_H0;")
            for i in range(k):
                w(f"\t\th = abi_mix(h, abi_sm({seed} + 100 + {i}));")
            w(f"\t\twant = abi_mix(hash_{name}(h, &s), abi_sm({seed} + 999));")
            w(f"\t\tgot = abi_rs_arg_{name}_{k}({args}s, abi_sm({seed} + 999));")
            w(f'\t\tif (got != want) {{ fails++; pr_err("ppc64abi: FAIL C->Rust arg {name} k={k}: %llx != %llx\\n", got, want); }}')
            w("\t}")
        seed = seed_of(si, 50)
        w("\t{")
        w(f"\t\t{kind} {name} r = abi_rs_ret_{name}({seed}), e = make_{name}({seed});")
        w(f"\t\tif (hash_{name}(0, &r) != hash_{name}(0, &e)) {{ fails++; pr_err(\"ppc64abi: FAIL C<-Rust ret {name}\\n\"); }}")
        w("\t}")
    w("\t(void)i;\n\treturn fails;\n}")
    # layout table
    w("const u64 abi_c_layout[] = {")
    for name, kind, attrs, fields in STRUCTS:
        w(f"\tsizeof({kind} {name}), __alignof__({kind} {name}),")
        for f, t, n in fields:
            w(f"\toffsetof({kind} {name}, {f}),")
    w("};")


def r_val(t, expr):
    if t == "bool":
        return f"({expr}) & 1 != 0"
    if t == "u128":
        return f"((({expr}) as u128) << 64) | sm({expr}) as u128"
    if t == "ptr":
        return f"core::ptr::without_provenance(({expr}) as usize)"
    return f"({expr}) as {RT[t]}"


def r_mix(t, expr):
    if t == "u128":
        return [f"h = mix(h, ({expr} >> 64) as u64);", f"h = mix(h, {expr} as u64);"]
    if t == "ptr":
        return [f"h = mix(h, {expr}.addr() as u64);"]
    if t.startswith("s"):
        return [f"h = mix(h, {expr} as i64 as u64);"]
    return [f"h = mix(h, u64::from({expr}));"]


def r_side(out):
    w = out.append
    w("// SPDX-License-Identifier: GPL-2.0\n// generated by gen_abi.py: do not edit")
    w("#![allow(non_camel_case_types, non_snake_case, clippy::all, clippy::pedantic, missing_docs)]")
    w("#![allow(clashing_extern_declarations, unused_unsafe, unused_mut, clippy::undocumented_unsafe_blocks)]")
    w("#![allow(improper_ctypes, improper_ctypes_definitions)] // u128 is part of what is tested")
    w("use super::{mix, sm, H0};\nuse kernel::prelude::*;")
    for si, (name, kind, attrs, fields) in enumerate(STRUCTS):
        rep = {"packed": "#[repr(C, packed)]", "aligned16": "#[repr(C, align(16))]", "": "#[repr(C)]"}[attrs]
        w(rep)
        w("#[derive(Clone, Copy)]")
        w(f"pub(crate) {kind} {name} {{")
        for f, t, n in fields:
            ty = RT[t] if n == 1 else f"[{RT[t]}; {n}]"
            w(f"    pub(crate) {f}: {ty},")
        w("}")
        w(f"fn make_{name}(seed: u64) -> {name} {{")
        if kind == "union":
            f, t, n = fields[0]
            w(f"    let mut v = [0 as {RT[t]}; {n}];")
            for fi, f2, t2, n2, j in elems(fields, kind):
                w(f"    v[{j}] = {r_val(t2, f'sm(seed ^ {key(fi, j)})')};")
            w(f"    {name} {{ {f}: v }}\n}}")
        else:
            w("    #[allow(unused_mut)]")
            inits = []
            for fi, (f, t, n) in enumerate(fields):
                if n == 1:
                    inits.append(f"{f}: {r_val(t, f'sm(seed ^ {key(fi, 0)})')}")
                else:
                    vs = ", ".join(r_val(t, f"sm(seed ^ {key(fi, j)})") for j in range(n))
                    inits.append(f"{f}: [{vs}]")
            w(f"    {name} {{ {', '.join(inits)} }}\n}}")
        w(f"fn hash_{name}(mut h: u64, s: &{name}) -> u64 {{")
        w(f"    let s = *s;")
        for fi, f, t, n, j in elems(fields, kind):
            base = f"(unsafe {{ s.{f} }})" if kind == "union" else f"s.{f}"
            ex = base + ("" if n == 1 else f"[{j}]")
            for line in r_mix(t, ex):
                w("    " + line)
        w("    h\n}")
        w("unsafe extern \"C\" {")
        for k in PLACEMENTS:
            params = "".join(f"p{i}: u64, " for i in range(k))
            w(f"    fn abi_c_arg_{name}_{k}({params}s: {name}, tail: u64) -> u64;")
        w(f"    fn abi_c_ret_{name}(seed: u64) -> {name};")
        w(f"    fn abi_c_cb_{name}(cb: unsafe extern \"C\" fn({name}, u64) -> u64, seed: u64) -> u64;")
        w(f"    fn abi_c_fnp_{name}() -> unsafe extern \"C\" fn({name}, u64) -> u64;")
        w("}")
        for k in PLACEMENTS:
            params = "".join(f"p{i}: u64, " for i in range(k))
            w("#[unsafe(no_mangle)]")
            w(f"unsafe extern \"C\" fn abi_rs_arg_{name}_{k}({params}s: {name}, tail: u64) -> u64 {{")
            w("    let mut h = H0;")
            for i in range(k):
                w(f"    h = mix(h, p{i});")
            w(f"    mix(hash_{name}(h, &s), tail)\n}}")
        w("#[unsafe(no_mangle)]")
        w(f"unsafe extern \"C\" fn abi_rs_ret_{name}(seed: u64) -> {name} {{ make_{name}(seed) }}")
    # Rust checks C
    w("pub(crate) fn check_c() -> u32 {\n    let mut fails = 0u32;")
    for si, (name, kind, attrs, fields) in enumerate(STRUCTS):
        for k in PLACEMENTS:
            seed = seed_of(si, k)
            args = "".join(f"sm({seed} + 100 + {i}), " for i in range(k))
            w("    {")
            w(f"        let s = make_{name}({seed});")
            w("        let mut h = H0;")
            for i in range(k):
                w(f"        h = mix(h, sm({seed} + 100 + {i}));")
            w(f"        let want = mix(hash_{name}(h, &s), sm({seed} + 999));")
            w(f"        // SAFETY: the C side has exactly this prototype (abi_gen_c.c).")
            w(f"        let got = unsafe {{ abi_c_arg_{name}_{k}({args}s, sm({seed} + 999)) }};")
            w(f'        if got != want {{ fails += 1; pr_err!("ppc64abi: FAIL Rust->C arg {name} k={k}: {{:x}} != {{:x}}\\n", got, want); }}')
            if k == 0:
                w(f"        // SAFETY: as above; the callback has the prototype C calls it with.")
                w(f"        let got = unsafe {{ abi_c_cb_{name}(abi_rs_arg_{name}_0, {seed}) }};")
                w(f"        let want = mix(hash_{name}(H0, &make_{name}({seed})), sm({seed} + 999));")
                w(f'        if got != want {{ fails += 1; pr_err!("ppc64abi: FAIL C->Rust fnptr {name}: {{:x}} != {{:x}}\\n", got, want); }}')
                w(f"        // SAFETY: C returns a pointer to abi_c_arg_{name}_0, which has this prototype.")
                w(f"        let got = unsafe {{ abi_c_fnp_{name}()(s, sm({seed} + 999)) }};")
                w(f'        if got != mix(hash_{name}(H0, &s), sm({seed} + 999)) {{ fails += 1; pr_err!("ppc64abi: FAIL Rust->C fnptr {name}\\n"); }}')
            w("    }")
        seed = seed_of(si, 50)
        w(f"    // SAFETY: as above.")
        w(f"    let r = unsafe {{ abi_c_ret_{name}({seed}) }};")
        w(f'    if hash_{name}(0, &r) != hash_{name}(0, &make_{name}({seed})) {{ fails += 1; pr_err!("ppc64abi: FAIL Rust<-C ret {name}\\n"); }}')
    w("    fails\n}")
    # layout
    w("unsafe extern \"C\" { static abi_c_layout: [u64; %d]; }" % sum(2 + len(f) for *_, f in STRUCTS))
    w("pub(crate) fn check_layout() -> u32 {\n    let rs: &[u64] = &[")
    for name, kind, attrs, fields in STRUCTS:
        w(f"        core::mem::size_of::<{name}>() as u64, core::mem::align_of::<{name}>() as u64,")
        for f, t, n in fields:
            w(f"        core::mem::offset_of!({name}, {f}) as u64,")
    w("    ];")
    w("    // SAFETY: abi_c_layout is an initialised constant array of this length (abi_gen_c.c).")
    w("    let c = unsafe { &abi_c_layout };")
    w("    let mut fails = 0u32;")
    w("    for (i, (a, b)) in rs.iter().zip(c.iter()).enumerate() {")
    w('        if a != b { fails += 1; pr_err!("ppc64abi: FAIL test-struct layout entry {}: rust {} gcc {}\\n", i, a, b); }')
    w("    }\n    fails\n}")
    w(f"pub(crate) const STRUCTS: usize = {len(STRUCTS)};")
    w(f"pub(crate) const CALLS: usize = {len(STRUCTS) * (len(PLACEMENTS) * 2 + 1 + 1 + 2)};")


def main():
    d = Path(sys.argv[1])
    for fn, gen in (("abi_gen.h", c_types), ("abi_gen_c.c", c_side), ("abi_gen.rs", r_side)):
        out = []
        gen(out)
        (d / fn).write_text("\n".join(out) + "\n")


main()
