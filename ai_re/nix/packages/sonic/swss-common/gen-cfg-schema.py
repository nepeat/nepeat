#!/usr/bin/env python3
"""cfg_schema.h without libyang: stand-in for upstream's gen_cfg_schema.py.

Upstream loads sonic-yang-models with sonic_yang (python libyang bindings,
not in nixpkgs) and emits one CFG_<TABLE>_TABLE_NAME macro per child
container of each module's top-level container. This reads the same .yang
(and .yang.j2) files textually and applies the same rule; the output format
is upstream's. Containers pulled in only through "uses" would be missed
(none are, for swss at the pinned revision: a missing macro fails the build).
usage: gen-cfg-schema.py -o OUT DIR...
"""
import argparse, glob, os, re

TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|\'[^\']*\'|\{%.*?%\}|\{#.*?#\}|//[^\n]*|/\*.*?\*/|[{};]|[^\s{};"\']+', re.S)

def tables(text):
    stack, words, found = [], [], set()
    for tok in TOKEN.findall(text):
        if tok.startswith(('//', '/*', '{%', '{#', '"', "'")):
            continue
        if tok == '{':
            stack.append(words[:2])
            words = []
        elif tok == '}':
            if stack:
                stack.pop()
            words = []
        elif tok == ';':
            words = []
        else:
            words.append(tok)
            # module M { container M { container TABLE {
            if (len(words) == 2 and words[0] == 'container' and len(stack) == 2
                    and stack[0][:1] == ['module'] and stack[1][:1] == ['container']):
                found.add(words[1])
    return found

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-o', required=True)
    ap.add_argument('dirs', nargs='+')
    a = ap.parse_args()
    keys = set()
    for d in a.dirs:
        for f in sorted(glob.glob(os.path.join(d, '*.yang')) + glob.glob(os.path.join(d, '*.yang.j2'))):
            with open(f) as fh:
                keys |= tables(fh.read())
    with open(a.o, 'w') as f:
        f.write('#ifndef CFG_SCHEMA_H\n#define CFG_SCHEMA_H\n\n'
                '// Macros for table names are autogenerated by gen_cfg_schema.py. Manual update will not be preserved.\n'
                '#ifdef __cplusplus\nnamespace swss {\n#endif\n\n')
        for key in sorted(keys):
            if '-' in key:
                f.write('// #define CFG_{}_TABLE_NAME "{}"\n'.format(key, key))
            else:
                f.write('#define CFG_{}_TABLE_NAME "{}"\n'.format(key, key))
        f.write('\n#ifdef __cplusplus\n}\n#endif\n#endif')

if __name__ == '__main__':
    main()
