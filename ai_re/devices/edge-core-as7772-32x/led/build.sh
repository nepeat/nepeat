#!/usr/bin/env bash
# Assemble the AS7772 LED programs and the test patterns, regenerate
# led_proc_init.soc and pattern-*.soc, and check them (ledcheck.py).
#   OPENBCM_SRC=<patched OpenBCM 6.5.27 tree: nix/packages/openbcm .src> led/build.sh [asm dir]
# asm dir: where led0.asm/led1.asm live and led_proc_init.soc is written
# (default nix/modules/boards/as7772/led). The assembler is the SDK's own
# tools/led/tools/ledasm.c, built here with the host gcc. See ../leds.md.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
src=${1:-$here/../../../nix/modules/boards/as7772/led}
sdk=${OPENBCM_SRC:?set OPENBCM_SRC to the OpenBCM sdk-6.5.27 tree}
factory=$here/../dumps/x/diag/root/usr/local/bin
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
gcc -w -I"$sdk/tools/led/tools" -o "$work/ledasm" "$sdk/tools/led/tools/ledasm.c"
assemble() { (cd "$work" && ./ledasm "$1" >"$1.log") || { cat "$work/$1.log"; exit 1; }
             grep -q ' 0 errors, 0 warnings' "$work/$1.log" || { cat "$work/$1.log"; exit 1; }; }
prog() { tr -s ' \n' ' ' <"$work/$1.hex" | sed -E 's/( 00)+ *$//; s/^ +//; s/ +$//'; }

cp "$src/led0.asm" "$src/led1.asm" "$work/"
assemble led0; assemble led1
{
  echo "# AS7772-32X front-panel port LEDs: our own LED processor programs (led0.asm, led1.asm in this"
  echo "# directory), generated by devices/edge-core-as7772-32x/led/build.sh with the OpenBCM SDK's ledasm."
  echo "# No port-order remap: the SDK's own (written by \"init all\") is the order the programs use."
  echo "# \"led auto on\": the SDK linkscan then keeps each port's link bit in the LED data RAM."
  echo "led 0 prog $(prog led0)"
  echo "led 0 start"
  echo "led 1 prog $(prog led1)"
  echo "led 1 start"
  echo "led auto on"
} >"$src/led_proc_init.soc"

pat() {  # name H1 C1 ON REST_C1 REST_ON
  sed -e "s/@H1@/$2/; s/@C1@/$3/; s/@ON@/$4/; s/@RC1@/$5/; s/@RON@/$6/" "$here/pattern.asm" >"$work/pattern-$1.asm"
  assemble "pattern-$1"
  {
    echo "# AS7772 port LED test pattern \"$1\" (pattern.asm, build.sh): all 32 cages, no inputs."
    echo "# Run with led-run.sh; back to normal with: led-run.sh <the system's led_proc_init.soc>"
    echo "led auto off"
    echo "led 0 stop"
    echo "led 1 stop"
    echo "led 0 prog $(prog "pattern-$1")"
    echo "led 1 prog $(prog "pattern-$1")"
    echo "led 0 start"
    echo "led 1 start"
  } >"$here/pattern-$1.soc"
}
pat blue   ONE  ONE  ONE  ZERO ZERO
pat yellow ONE  ZERO ONE  ZERO ZERO
pat cyan   ZERO ONE  ONE  ONE  ONE
pat green  ZERO ZERO ONE  ZERO ONE
pat off    ZERO ONE  ZERO ONE  ZERO

if [ -d "$factory" ]; then python3 -I "$here/ledcheck.py" "$work" "$factory"
else python3 -I "$here/ledcheck.py" "$work"; fi
sha256sum "$src/led_proc_init.soc"
