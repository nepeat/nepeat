#!/usr/bin/env python3
"""Build a libsai (Credo SAI 1.2.12) XML switch profile for one Owl 800 slice
from the 2021 vendor command files, and/or verify the register encoding of
those settings against a libMdio trace of the vendor bring-up.

usage:
  vendor-profile.py --sdk C_PHY_DIR --phy 0x02 [--msb laneopt|serdes|none] [--no-taps]
                    [--no-polarity] [--port] [-o out.xml]
  vendor-profile.py --sdk C_PHY_DIR --verify trace.txt[.gz]

C_PHY_DIR is the vendor c-phy/ directory (swap_setting.cmd,
preemphasis_PAM4_400G_32_HostLT.cmd, preemphasis_PAM4_400G_32_Optics.cmd;
the 0.1.7 SDK that produced our trace: -m 1-32:optics_1x400G:fec-def
-e macsecbypass -l).

Vendor slice_id -> PHY address (from the 2026-11-10 trace: polarity masks and
taps of all 16 slices, see README step 2): slices 1-8 are swapped in pairs
(slice 1 -> PHY 0x03, slice 2 -> PHY 0x02, ...), slices 9-16 -> slice+1.

Register encoding (per lane L, base L*0x200, lanes 0-7 host, 12-19 line):
  +0x043 bit 7   RX polarity inverted        (= rx_pol_mask bit L)
  +0x161 bit 14  RX polarity inverted        (same value, written together)
  +0x0a0 bit 5   TX polarity NOT inverted    (= !tx_pol_mask bit L)
  +0x0af bit 10  TX MSB/LSB swap (set_tx_msb)
  +0x043 bit 15  RX MSB/LSB swap (set_rx_msb)
  +0x0a5/a7/a9/ab/ad bits 15:8  TX taps pre2/pre1/main/post1/post2 (s8)
"""
import argparse, gzip, re, sys

HOST = list(range(8))
LINE = list(range(12, 20))
LANES = HOST + LINE


def phy_of_slice(s):
    if s <= 8:
        return s + 2 if s % 2 else s
    return s + 1


def slice_of_phy(p):
    return next(s for s in range(1, 17) if phy_of_slice(s) == p)


def load_vendor(sdk):
    pol = {}
    for m in re.finditer(r'slice_id=(\d+) lane_mask=0x(\w+) rx_pol_mask=0b([01]+) tx_pol_mask=0b([01]+)',
                         open(f'{sdk}/swap_setting.cmd').read()):
        lm = int(m[2], 16)
        pol[int(m[1])] = (int(m[3], 2) & lm, int(m[4], 2) & lm)
    taps = {}
    for fn in ('preemphasis_PAM4_400G_32_HostLT.cmd', 'preemphasis_PAM4_400G_32_Optics.cmd'):
        for m in re.finditer(r'set_tx_taps slice_id=(\d+) lane=(\d+) taps=([-\d,]+)', open(f'{sdk}/{fn}').read()):
            taps[(int(m[1]), int(m[2]))] = [int(x) for x in m[3].split(',')]
    return pol, taps


def expected(sl, pol, taps):
    """register -> (mask, value) the vendor bring-up should leave behind"""
    rx, tx = pol[sl]
    exp = {}
    def put(r, mask, val):
        m0, v0 = exp.get(r, (0, 0))
        exp[r] = (m0 | mask, (v0 & ~mask) | (val & mask))
    for L in LANES:
        b = L * 0x200
        put(b + 0x43, 0x0080, 0x0080 if rx >> L & 1 else 0)
        put(b + 0x161, 0x4000, 0x4000 if rx >> L & 1 else 0)
        put(b + 0xa0, 0x0020, 0 if tx >> L & 1 else 0x0020)
        if L in HOST:
            put(b + 0xaf, 0x0400, 0x0400)
        else:
            # the host sets bit 10 here too, but the MCU rewrites line lanes
            # to 0xfa09 (bits 10:9 = 01) during firmware_configure_port
            put(b + 0xaf, 0x0600, 0x0200)
        put(b + 0x43, 0x8000, 0x8000)
        for i, t in enumerate(taps[(sl, L)]):
            put(b + 0xa5 + 2 * i, 0xff00, (t & 0xff) << 8)
    return exp


def verify(trace, pol, taps):
    last = {}
    op = gzip.open if trace.endswith('.gz') else open
    for line in op(trace, 'rt'):
        t, rw, phy, reg, val, ret = line.split()
        if ret == '0':
            last[(int(phy, 16), int(reg, 16))] = int(val, 16)
    bad = total = 0
    for p in range(2, 18):
        sl = slice_of_phy(p)
        exp = expected(sl, pol, taps)
        nb = 0
        for r, (m, v) in sorted(exp.items()):
            total += 1
            got = last.get((p, r))
            if got is None or got & m != v:
                nb += 1
                print(f'  PHY {p:02x} slice {sl:2d} reg {r:04x} mask {m:04x} want {v:04x} got '
                      + ('----' if got is None else f'{got & m:04x}'))
        bad += nb
        print(f'PHY 0x{p:02x} <- vendor slice {sl:2d}: {len(exp) - nb}/{len(exp)} registers match')
    print(f'total {total - bad}/{total} match')
    return bad == 0


def profile(sl, pol, taps, msb='laneopt', use_taps=True, polarity=True, port=False, port_opts=(), port_mode=None):
    rx, tx = pol[sl]
    o = ['<?xml version="1.0"?>',
         f'<!-- Generated by vendor-profile.py: one Owl 800 slice, PHY address 0x{phy_of_slice(sl):02x}',
         f'     = vendor slice_id {sl}. Host lanes 0-7, line lanes 12-19 (lane_mask 0xff0ff), retimer.',
         f'     rx_pol_mask 0x{rx:05x}, tx_pol_mask 0x{tx:05x}; taps from preemphasis_PAM4_400G_32_HostLT/Optics. -->',
         '<root>', '    <name>owl800</name>', '    <phy_addr>0</phy_addr>', '    <mode>retimer</mode>']
    if msb == 'serdes':
        # parsed but never applied: SetSerdesParams() is a stub in 1.2.12
        o.append('    <serdes_parameters>')
        for L in LANES:
            o.append(f'        <serdes_parameter id="{L}" name="tx_msblsb" type="int" value="1" />')
            o.append(f'        <serdes_parameter id="{L}" name="rx_msblsb" type="int" value="1" />')
        o.append('    </serdes_parameters>')
    if use_taps:
        o.append('    <PAM4>')
        for L in LANES:
            o.append(f'        <lane id="{L}" tx-taps="{",".join(str(x) for x in taps[(sl, L)])}" />')
        o.append('    </PAM4>')
    for L in LANES:
        side = 'true' if L in HOST else 'false'
        attrs = f'id="{L}" system-side="{side}"'
        if polarity:
            t = 'true' if tx >> L & 1 else 'false'
            r = 'true' if rx >> L & 1 else 'false'
            attrs += f' tx-polarity="{t}" rx-polarity="{r}"'
        if msb == 'laneopt':
            o.append(f'    <lane {attrs}>')
            o.append('        <option name="tx_msblsb" value="1" />')
            o.append('        <option name="rx_msblsb" value="1" />')
            o.append('    </lane>')
        else:
            o.append(f'    <lane {attrs} />')
    if port:
        o += ['    <port-connector>',
              '        <system-side lane-number="0,1,2,3,4,5,6,7" speed="400000" fec="rs544" />',
              '        <line-side lane-number="12,13,14,15,16,17,18,19" speed="400000" fec="rs544" />']
        if port_mode:
            o.append(f'        <mode>{port_mode}</mode>')
        if port_opts:
            o.append('        <options>')
            for kv in port_opts:
                k, v = kv.split('=', 1)
                o.append(f'            <option name="{k}" value="{v}" />')
            o.append('        </options>')
        o.append('    </port-connector>')
    o.append('</root>')
    return '\n'.join(o) + '\n'


ap = argparse.ArgumentParser()
ap.add_argument('--sdk', required=True)
ap.add_argument('--phy', type=lambda x: int(x, 0))
ap.add_argument('--verify')
ap.add_argument('--msb', choices=('laneopt', 'serdes', 'none'), default='laneopt')
ap.add_argument('--no-taps', action='store_true')
ap.add_argument('--no-polarity', action='store_true')
ap.add_argument('--port', action='store_true')
ap.add_argument('--port-opt', action='append', default=[], help='port-connector option NAME=VALUE (e.g. host_lt=1)')
ap.add_argument('--port-mode')
ap.add_argument('-o')
a = ap.parse_args()
pol, taps = load_vendor(a.sdk)
if a.verify:
    sys.exit(0 if verify(a.verify, pol, taps) else 1)
x = profile(slice_of_phy(a.phy), pol, taps, a.msb, not a.no_taps, not a.no_polarity, a.port, a.port_opt, a.port_mode)
if a.o:
    open(a.o, 'w').write(x)
else:
    sys.stdout.write(x)
