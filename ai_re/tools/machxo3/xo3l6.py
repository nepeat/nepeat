#!/usr/bin/env python3
"""Layer 6: re-roll replicated structures of an L4 netlist into templates + instances. Generic.

  xo3l6.py extract NET-L4.json OUTDIR [--rounds N] [--min-family 2]
  xo3l6.py rebuild OUTDIR OUT.json          inverse: L6 -> L4 netlist (compare with xo3l4.py same)

Input: the lossless L4 netlist of xo3l4.py (cells with cfg + owned config lines, nets
with owned arcs).  Output (OUTDIR):
  template.json   families: {fam: {elements: [...], ports: [...], members: [...], reference}}
  inst/<fam>__<k>.json   one per instance: placement, bindings, routing (nets), deviations
  remainder.json  every cell and net that no instance generates, raw, + the L4 header data
  report.txt      families, coverage per instance, deviations, encoder check
  instances.txt   per instance: cells covered (element -> cell) and port bindings

What an instance regenerates (from the template + its placement) and what it stores:
  generated  cell `cfg` (logical keys from the template: the most common cfg of that
             element over the members; LUT/CCU2 INIT regenerated by permuting the
             reference INIT with the pin permutation implied by the routing: template net
             on each template pin -> bound design net -> the instance cell's pin carrying
             it; unrouted pins paired in sorted order, CCU2 pins only within {A,B} and
             {C,D}; slice-shared keys (MODE, the FF control muxes, GSR, REGMODE, WREMUX)
             of a K1/FF1 taken from its slice's K0/FF0, which owns them) and `config` (the
             cell's owned enum/word/unknown lines, encoded from cfg + slice/site position +
             tile, see `encode`; `report.txt` states how many design cells it reproduces)
  stored     placement per element: cell name, site type, bel, x, y, z, dirs, pins
             (routing), tile of its config lines, packing keys (SD = M/DI data input,
             WREMUX), unknown bits of a pad; the net records the instance's cells drive
             (arcs); bindings template net -> design net
  deviation  an element whose regenerated cell differs from the original keeps its raw
             cell (with the differing keys); extract verifies every generated element
             against the original, and `rebuild` + `xo3l4.py same` checks the whole netlist.

Discovery (structural, no names of a design):
  seeds    (1) every CCU2 carry chain (FCO -> FCI links between CCU2 halves; the chain
           starts at a half whose FCI is not a CCU2 FCO); (2) every tile with IOLOGIC
           tristate registers (TS used, pad TRIMUX_TSREG = IOLTO) with those pads.
  chains   + FFs whose data input is a chain sum; then `rounds` passes of backward-private
           growth (a slice cell joins seed i when every sink of its outputs is in seed i);
           family = same chain length + per-half canonical CCU2 function over the routed
           pins; alignment to the reference by seeded propagation (chain position, then
           neighbours over equal edge labels, Weisfeiler-Lehman colours as tie-breaker:
           strict colours = kind + logical cfg + canonical LUT function, then loose ones =
           kind only, so cfg differences become deviations instead of a smaller template).
  IOL      family = same number of TS registers (--iol-merge: all IOL tiles in one family);
           k-way alignment over the whole design (`kway`): tuples of one cell per member
           grow from the pads while every member has exactly one matching candidate and all
           are distinct, unowned cells; a cell reached by two members is shared logic and
           stops the growth there (--max-hop bounds the depth).
  Template = reference elements matched in every member; the rest of a grown membership
  stays in the remainder.  Families with fewer than --min-family members are not re-rolled.
"""
import json, os, re, sys, argparse, itertools, hashlib, collections

SLICE_RE = re.compile(r'^(R\d+C\d+)_SLICE([A-D])\.(K0|K1|FF0|FF1)$')
PHYS_KEYS = ('SD', 'WREMUX')
LUTP = ('A', 'B', 'C', 'D')
FF0_SHARED = {'CLK.CLKMUX': 'CLK{n}.CLKMUX', 'CE.CEMUX': 'CE{n}.CEMUX', 'LSR.LSRMUX': 'LSR{n}.LSRMUX',
              'LSR.LSRONMUX': 'LSR{n}.LSRONMUX', 'LSR.SRMODE': 'LSR{n}.SRMODE', 'GSR': 'SLICE{L}.GSR',
              'REGMODE': 'SLICE{L}.REGMODE', 'WREMUX': 'SLICE{L}.WREMUX'}


# ---------------------------------------------------------------- encoding of config lines
def encode(name, cell, tile):
    """config lines [[tile, line]] of a cell from its type, cfg and position; None if the
    cell type has no encoder (it is then never generated)."""
    cf = cell['cfg']
    out = []
    m = SLICE_RE.match(name)
    if m:
        L, role = m.group(2), m.group(3)
        n = 'ABCD'.index(L)
        if role[0] == 'K':
            k = role[1]
            if 'INIT' in cf:
                out.append('word: SLICE%s.K%s.INIT %s' % (L, k, cf['INIT']))
            if 'INJECT1' in cf:
                out.append('enum: SLICE%s.CCU2.INJECT1_%s %s' % (L, k, cf['INJECT1']))
            if k == '0' and 'MODE' in cf:
                out.append('enum: SLICE%s.MODE %s' % (L, cf['MODE']))
        else:
            i = role[2]
            if 'REGSET' in cf:
                out.append('enum: SLICE%s.REG%s.REGSET %s' % (L, i, cf['REGSET']))
            if 'SD' in cf:
                out.append('enum: SLICE%s.REG%s.SD %s' % (L, i, cf['SD']))
            if i == '0':
                for key, fmt in FF0_SHARED.items():
                    if key in cf:
                        out.append('enum: %s %s' % (fmt.format(n=n, L=L), cf[key]))
    elif cell['type'] in ('PIO', 'IOLOGIC', 'TIOLOGIC', 'BIOLOGIC', 'TSIOLOGIC'):
        bel = cell.get('bel', '')
        site = re.sub(r'^(TS|T|B)(?=IOLOGIC)', '', bel)
        for key, v in cf.items():
            out.append('enum: %s.%s %s' % (site, key, v))
    elif cell['type'] == 'TILE':
        out = ['enum: %s %s' % (k, v) for k, v in cf.items()]
    else:
        out = ['enum: %s.%s %s' % (cell['type'], k, v) for k, v in cf.items()]
    for b in cell.get('unknown_bits', ()):
        out.append('unknown: %s' % (b[0] if isinstance(b, list) else b))
    if out and tile is None:
        return None
    return sorted([tile, l] for l in out)


def cell_tile(cell):
    ts = {t for t, _ in cell.get('config', [])}
    return ts.pop() if len(ts) == 1 else None


# ---------------------------------------------------------------- logical view
def kind(cell):
    t, cf = cell['type'], cell['cfg']
    if t == 'TRELLIS_COMB':
        return 'CCU2' if cf.get('MODE') == 'CCU2' else 'LUT'
    if t == 'TRELLIS_FF':
        return 'LATCH' if cf.get('REGMODE') == 'LATCH' else 'FF'
    if 'IOLOGIC' in t:
        return 'IOL'
    return t


def logical_inputs(name, cell, nets=None):
    """[(role, pin)] of pins that carry logic (not the RAM/WAD wires of a slice; the
    PFUMX/L6MUX inputs only when the cell's OFX output is used)."""
    k, pins, cf = kind(cell), cell['pins'], cell['cfg']
    if k in ('LUT', 'CCU2'):
        r = [('L', p) for p in LUTP if p in pins]
        if k == 'CCU2' and 'FCI' in pins:
            r.append(('FCI', 'FCI'))
        if k == 'LUT' and ofx_used(name, cell, nets):
            for p in (('M', 'F1') if name.endswith('K0') else ('M', 'FXA', 'FXB')):
                if p in pins:
                    r.append((p, p))
        return r
    if cell['type'] == 'TRELLIS_RAMW':
        return []
    if k in ('FF', 'LATCH'):
        d = 'M' if cf.get('SD') == '0' else 'DI'
        return [(p if p != d else 'D', p) for p in ('CLK', 'CE', 'LSR', d) if p in pins]
    return [(p, p) for p, dd in cell['dirs'].items() if dd == 'in' and p in pins]


def ofx_used(name, cell, nets, depth=0):
    """the PFUMX/L6MUX output of a LUT cell drives logic: an FF data/CE/LSR pin, a LUT
    input, a pad/IO pin, or the FXA/FXB of an L6MUX whose own OFX is used."""
    if nets is None:
        return True
    o = cell['pins'].get('OFX')
    if o not in nets or depth > 3:
        return False
    for sk in nets[o].get('sinks', []):
        c, p = sk.rsplit('.', 1)
        if p in LUTP or p in ('DI', 'CE', 'LSR', 'I', 'T', 'TS', 'OPOS', 'CLK'):
            return True
        if p == 'M' and '.FF' in c:
            return True
        if p in ('FXA', 'FXB') and c in _CELLS and ofx_used(c, _CELLS[c], nets, depth + 1):
            return True
    return False


_CELLS = {}


def shared_owner(name, key):
    """slice-shared cfg keys: the cell whose cfg/config owns the key (K0 for MODE, FF0 for
    the FF control muxes, GSR, REGMODE, WREMUX); None when the cell owns it itself."""
    m = SLICE_RE.match(name)
    if not m:
        return None
    base = '%s_SLICE%s.' % (m.group(1), m.group(2))
    own = 'K0' if key == 'MODE' else 'FF0' if (key in FF0_SHARED) else None
    if own is None or m.group(3) == own:
        return None
    return base + own


def init_int(s):
    return int(s, 2)


def init_str(v):
    return format(v, '016b')


def perm_init(init, pi):
    """pi: ref pin index -> member pin index (0..3); returns member INIT (int)."""
    out = 0
    for ib in range(16):
        ia = 0
        for pa in range(4):
            if (ib >> pi[pa]) & 1:
                ia |= 1 << pa
        if (init >> ia) & 1:
            out |= 1 << ib
    return out


def restricted(init, routed):
    """truth table over the routed pins (unrouted = 0), routed = list of pin indices."""
    t = 0
    for i in range(1 << len(routed)):
        idx = 0
        for j, p in enumerate(routed):
            if (i >> j) & 1:
                idx |= 1 << p
        if (init >> idx) & 1:
            t |= 1 << i
    return t


def canon_lut(cell):
    cf = cell['cfg']
    init = init_int(cf.get('INIT', '0' * 16))
    routed = [i for i, p in enumerate(LUTP) if p in cell['pins']]
    best = None
    for perm in itertools.permutations(routed):
        t = restricted(init, list(perm))
        if kind(cell) == 'CCU2':
            g = restricted((~(init >> 12)) & 0xF, [p for p in perm if p < 2])
            t = (t, g)
        best = t if best is None or t < best else best
    return (len(routed), best)


def lsig(cell):
    cf = {k: v for k, v in cell['cfg'].items() if k not in PHYS_KEYS and k != 'INIT'}
    return json.dumps(cf, sort_keys=True)


# ---------------------------------------------------------------- design graph
class Graph:
    def __init__(self, net):
        self.C = net['cells']
        self.N = net['nets']
        _CELLS.clear(); _CELLS.update(self.C)
        self.inp = {}            # cell -> [(role, pin, net)]
        self.sinks = collections.defaultdict(list)   # driver cell -> [(sinkcell, role)]
        self.drv = {}            # net -> driver cell
        for n, nr in self.N.items():
            d = nr.get('driver')
            if d:
                self.drv[n] = d.rsplit('.', 1)[0]
        for c, cell in self.C.items():
            r = []
            for role, p in logical_inputs(c, cell, self.N):
                nn = cell['pins'].get(p)
                if nn and not nn.startswith('undriven:'):
                    r.append((role, p, nn))
                    d = self.drv.get(nn)
                    if d in self.C:
                        self.sinks[d].append((c, role))
            self.inp[c] = r

    def driver(self, net):
        return self.drv.get(net)


def chains(G):
    cc = {n for n, c in G.C.items() if kind(c) == 'CCU2'}
    nxt = {}
    for n in cc:
        f = G.C[n]['pins'].get('FCI')
        d = G.driver(f) if f else None
        if d in cc and f == d + '.FCO':
            nxt[d] = n
    has_prev = set(nxt.values())
    out = []
    for s in sorted(cc - has_prev):
        ch = [s]
        while ch[-1] in nxt:
            ch.append(nxt[ch[-1]])
        out.append(ch)
    return out


def iol_seeds(G):
    by = collections.defaultdict(list)
    for n, c in G.C.items():
        if kind(c) == 'IOL' and 'TS' in c['pins']:
            to = n + '.IOLTO'
            if any(p['type'] == 'PIO' and p['cfg'].get('TRIMUX_TSREG') == 'IOLTO' and p['pins'].get('T') == to
                   for p in (G.C.get(x.rsplit('.', 1)[0], {'type': ''}) for x in G.N.get(to, {}).get('sinks', []))):
                by[n.split('_')[0]].append(n)
    seeds = []
    for t, ios in sorted(by.items()):
        s = list(ios)
        for n, c in G.C.items():
            if c['type'] == 'PIO' and n.startswith(t + '_') and c['cfg'].get('TRIMUX_TSREG') == 'IOLTO' \
                    and c['pins'].get('T') in {i + '.IOLTO' for i in ios}:
                s.append(n)
        seeds.append(sorted(s))
    return seeds


def grow(G, seeds, chain_flags, rounds):
    owner = {}
    for i, s in enumerate(seeds):
        for c in s:
            owner[c] = i
    # forward: counter FFs whose data input is a chain sum
    for i, s in enumerate(seeds):
        if not chain_flags[i]:
            continue
        for c in list(s):
            for sk, role in G.sinks.get(c, ()):
                if role == 'D' and kind(G.C[sk]) == 'FF' and sk not in owner:
                    owner[sk] = i; s.append(sk)
    for _ in range(rounds):
        add = []
        for c, cell in G.C.items():
            if c in owner or cell['type'] not in ('TRELLIS_COMB', 'TRELLIS_FF'):
                continue
            sk = G.sinks.get(c)
            if not sk:
                continue
            os_ = {owner.get(x) for x, _ in sk}
            if len(os_) == 1 and None not in os_:
                add.append((c, os_.pop()))
        if not add:
            break
        for c, i in add:
            owner[c] = i; seeds[i].append(c)
    return seeds


# ---------------------------------------------------------------- alignment
def H(*a):
    return hashlib.sha1(repr(a).encode()).hexdigest()[:16]


def wl(G, members, seedlab, globals_, rounds=6, strict=True):
    """per-round colours of every cell of an instance (members: set): list of dicts.
    strict: initial colour includes logical cfg and canonical LUT function; loose: kind only."""
    col = {}
    for c in members:
        cell = G.C[c]
        k = kind(cell)
        f = canon_lut(cell) if k in ('LUT', 'CCU2') else None
        col[c] = H(k, lsig(cell), f) if strict else H(k, len(G.inp[c]))
    hist = [col]
    for _ in range(rounds):
        new = {}
        for c in members:
            ins = []
            for role, p, nn in G.inp[c]:
                d = G.driver(nn)
                if d in members:
                    ins.append((role, col[d], nn.rsplit('.', 1)[1]))
                else:
                    ins.append((role, 'G:' + nn if nn in globals_ else 'X'))
            outs = sorted((role, col[s]) for s, role in G.sinks.get(c, ()) if s in members)
            new[c] = H(col[c], sorted(ins), outs)
        col = new
        hist.append(col)
    return hist


def edges(G, c, members):
    """(edge label, neighbour) of a cell inside members."""
    r = []
    for role, p, nn in G.inp[c]:
        d = G.driver(nn)
        if d in members:
            r.append((('i', role, p if role not in ('L', 'D') else '', nn.rsplit('.', 1)[1]), d))
    for s, role in G.sinks.get(c, ()):
        if s in members:
            sp = [p for rr, p, nn in G.inp[s] if rr == role and G.driver(nn) == c]
            r.append((('o', role, sp[0] if sp and role not in ('L', 'D') else ''), s))
    return r


def align(G, ref, mem, href, hmem, lref, lmem, m=None, maxhop=99, hop=None):
    """seeded propagation: seed labels first, then neighbours over equal edge labels whose
    colours agree at the deepest round that separates the candidates (at most maxhop edges
    from a seed)."""
    m = dict(m or {})
    hop = hop if hop is not None else {}
    bl = collections.defaultdict(list)
    for c in mem:
        if c in lmem:
            bl[lmem[c]].append(c)
    for c in ref:
        if c not in m and c in lref and len(bl.get(lref[c], ())) == 1 and kind(G.C[c]) == kind(G.C[bl[lref[c]][0]]):
            m[c] = bl[lref[c]][0]; hop[c] = 0
    used = set(m.values())
    R = len(href)
    changed = True
    while changed:
        changed = False
        for a in list(m):
            b = m[a]
            if hop.get(a, 0) >= maxhop:
                continue
            ea = collections.defaultdict(list)
            for lab, x in edges(G, a, ref):
                if x not in m:
                    ea[lab].append(x)
            eb = collections.defaultdict(list)
            for lab, y in edges(G, b, mem):
                if y not in used:
                    eb[lab].append(y)
            for lab, xs in ea.items():
                ys = eb.get(lab, [])
                for x in xs:
                    if x in m:
                        continue
                    cands = [y for y in ys if y not in used and href[0][x] == hmem[0][y]]
                    r = 1
                    while len(cands) > 1 and r < R:
                        c2 = [y for y in cands if href[r][x] == hmem[r][y]]
                        if not c2:
                            break
                        cands = c2; r += 1
                    others = [x2 for x2 in xs if x2 != x and x2 not in m and any(href[min(r, R) - 1][x2] == hmem[min(r, R) - 1][y] for y in cands)]
                    if len(cands) == 1 and cands[0] == x:
                        continue      # the same cell on both sides: shared logic, not an instance
                    if len(cands) == 1 and not others:
                        m[x] = cands[0]; used.add(cands[0]); changed = True
                        hop[x] = hop.get(a, 0) + 1
    return m


def kway(G, seedsets, labels, hs, hl, universe, maxhop):
    """k-way seeded alignment over the whole design: tuples (one cell per member) grow over
    equal edge labels while every member has exactly one candidate with the reference's
    colour (strict colours first, then loose), all candidates are distinct cells outside
    every tuple so far (a cell reached by two members is shared logic: growth stops there).
    Returns [ {ref_cell: member_cell} per member ], member 0 = reference (identity)."""
    k = len(seedsets)
    tuples = []
    owned = set()
    lab_inv = [collections.defaultdict(list) for _ in range(k)]
    for j in range(k):
        for c, l in labels[j].items():
            lab_inv[j][l].append(c)
    for c, l in labels[0].items():
        t = [c] + [lab_inv[j][l][0] if len(lab_inv[j][l]) == 1 else None for j in range(1, k)]
        if None not in t and len(set(t)) == k and all(kind(G.C[x]) == kind(G.C[c]) for x in t):
            tuples.append((tuple(t), 0)); owned |= set(t)
    R = len(hs)
    i = 0
    for cols in (hs, hl):
        i = 0
        frontier = list(tuples)
        while frontier:
            nxt = []
            for t, hop in frontier:
                if hop >= maxhop:
                    continue
                E = []
                for j in range(k):
                    e = collections.defaultdict(list)
                    for lab, y in edges(G, t[j], universe):
                        e[lab].append(y)
                    E.append(e)
                for lab, xs in E[0].items():
                    for x in xs:
                        if x in owned:
                            continue
                        new = [x]
                        for j in range(1, k):
                            cands = [y for y in E[j].get(lab, []) if cols[0][x] == cols[0][y]]
                            r = 1
                            while len(cands) > 1 and r < R:
                                c2 = [y for y in cands if cols[r][x] == cols[r][y]]
                                if not c2:
                                    break
                                cands = c2; r += 1
                            rivals = [x2 for x2 in xs if x2 != x and cols[r - 1][x2] == cols[r - 1][x]]
                            if len(cands) != 1 or rivals:
                                new = None; break
                            new.append(cands[0])
                        if new is None or len(set(new)) != k or owned & set(new):
                            continue
                        tt = (tuple(new), hop + 1)
                        tuples.append(tt); nxt.append(tt); owned |= set(new)
            frontier = nxt
    return [{t[0]: t[j] for t, _ in tuples} for j in range(k)]


# ---------------------------------------------------------------- template + instances
def lut_pi(tel, cell, bind, tnet_of_pin):
    """pin permutation ref -> member implied by the bindings; None if not determined."""
    ccu = tel['kind'] == 'CCU2'
    pi = [None] * 4
    usedq = set()
    for pa in range(4):
        t = tnet_of_pin.get(LUTP[pa])
        if t is None:
            continue
        want = bind.get(t)
        q = None
        for qb in range(4):
            if qb not in usedq and cell['pins'].get(LUTP[qb]) == want and want is not None:
                q = qb; break
        if q is None:
            return None
        pi[pa] = q; usedq.add(q)
    groups = [(0, 1), (2, 3)] if ccu else [(0, 1, 2, 3)]
    for g in groups:
        ra = [p for p in g if pi[p] is None]
        rb = [q for q in g if q not in usedq] if ccu else [q for q in range(4) if q not in usedq]
        if len(ra) != len(rb):
            return None
        for p, q in zip(ra, sorted(rb)):
            pi[p] = q; usedq.add(q)
    if ccu and any((p < 2) != (pi[p] < 2) for p in range(4)):
        return None
    return pi


def gen_cell(tel, pl, bind, cells):
    """regenerate one element's cell from template element + placement + bindings; slice-
    shared keys come from the owner cell of the slice (cells: the netlist being built)."""
    cfg = {k: v for k, v in tel['cfg'].items() if shared_owner(pl['cell'], k) is None}
    for k, v in pl.get('phys', {}).items():
        if shared_owner(pl['cell'], k) is None:
            cfg[k] = v
    for k in pl.get('shared', ()):
        o = shared_owner(pl['cell'], k)
        if o not in cells or k not in cells[o]['cfg']:
            return None
        cfg[k] = cells[o]['cfg'][k]
    if tel['kind'] in ('LUT', 'CCU2') and 'INIT' in tel['cfg']:
        pi = lut_pi(tel, pl, bind, tel['tnet_of_pin'])
        if pi is None:
            return None
        cfg['INIT'] = init_str(perm_init(init_int(tel['cfg']['INIT']), pi))
    cell = {'type': pl.get('type', tel['type']), 'cfg': cfg, 'pins': pl['pins'], 'dirs': pl['dirs']}
    for k in ('bel', 'x', 'y', 'z', 'tile', 'unknown_bits'):
        if k in pl:
            cell[k] = pl[k]
    enc = encode(pl['cell'], cell, pl.get('cfgtile'))
    if enc is None:
        return None
    cell['config'] = enc
    return cell


def extract(net, outdir, rounds, minfam, maxhop=40, iol_merge=False):
    G = Graph(net)
    C = G.C
    # encoder check over the whole design
    enc_ok = sum(1 for n, c in C.items() if encode(n, c, cell_tile(c)) == c['config'])
    ch = chains(G)
    seeds, flags, labels, kinds = [], [], [], []
    for c in ch:
        sig = ('chain', len(c), tuple(canon_lut(C[h]) for h in c))
        seeds.append(list(c)); flags.append(True); kinds.append(sig)
        labels.append({h: ('pos', i) for i, h in enumerate(c)})
    for s in iol_seeds(G):
        nts = sum(1 for x in s if kind(C[x]) == 'IOL')
        seeds.append(list(s)); flags.append(False)
        kinds.append(('iol', 0 if iol_merge else nts))
        lab = {}
        for x in s:
            if kind(C[x]) == 'IOL':
                pads = [p for p in s if C[p]['type'] == 'PIO' and C[p]['pins'].get('T') == x + '.IOLTO']
                lab[x] = ('iol', tuple(C[p]['cfg'].get('BASE_TYPE', '') for p in pads))
            else:
                lab[x] = ('pad', C[x]['cfg'].get('BASE_TYPE', ''))
        labels.append(lab)
    seeds = grow(G, seeds, flags, rounds)
    fams = collections.defaultdict(list)
    for i, k in enumerate(kinds):
        fams[k].append(i)
    fam_names = {}
    templates, instances = {}, []
    taken = set()
    fi = collections.Counter()
    for k, idx in sorted(fams.items(), key=lambda kv: (kv[0][0], kv[0][1], -len(kv[1]))):
        if len(idx) < minfam:
            continue
        base = ('chain%d' % k[1]) if k[0] == 'chain' else ('iol%d' % k[1])
        fi[base] += 1
        fname = '%s%s' % (base, chr(ord('a') + fi[base] - 1))
        if k[0] == 'iol':
            universe = {c for c, cl in C.items() if c not in taken and cl['type'] not in ('TRELLIS_RAMW',)}
            mems = [universe for i in idx]
        else:
            mems = [set(seeds[i]) for i in idx]
        # externals that feed every member: named in the colouring
        ext = []
        for ms in ([set(seeds[i]) for i in idx] if k[0] == 'iol' else mems):
            e = set()
            for c in ms:
                for _, _, nn in G.inp[c]:
                    if G.driver(nn) not in ms:
                        e.add(nn)
            ext.append(e)
        glob = set.intersection(*ext) if ext else set()
        if k[0] == 'iol':
            cols = [wl(G, universe, None, glob)]
            loose = [wl(G, universe, None, glob, strict=False)]
        else:
            cols = [wl(G, ms, labels[i], glob) for ms, i in zip(mems, idx)]
            loose = [wl(G, ms, labels[i], glob, strict=False) for ms, i in zip(mems, idx)]
        order = sorted(range(len(idx)), key=lambda j: min(seeds[idx[j]]))
        r = order[0]
        maps = {}
        if k[0] == 'iol':
            kw = kway(G, [set(seeds[idx[j]]) for j in order], [labels[idx[j]] for j in order],
                      cols[0], loose[0], universe, maxhop)
            for n_, j in enumerate(order):
                maps[j] = kw[n_]
            mems = [None] * len(idx)
            for j in order:
                mems[j] = set(maps[j].values())
        else:
            for j in order:
                if j == r:
                    maps[j] = {c: c for c in mems[r]}
                    continue
                m1 = align(G, mems[r], mems[j], cols[r], cols[j], labels[idx[r]], labels[idx[j]])
                maps[j] = align(G, mems[r], mems[j], loose[r], loose[j], labels[idx[r]], labels[idx[j]], m1)
        core = [c for c in sorted(mems[r]) if all(c in maps[j] for j in order)]
        if os.environ.get('L6_DEBUG'):
            print('family', k[:2], len(idx), 'grown', [len(x) for x in mems], 'matched', [len(maps[j]) for j in order], 'core', len(core))
        if not core:
            continue
        eid = {c: 'e%d' % n for n, c in enumerate(core)}
        # template nets: internal = e<k>.<pin>; ports = p<k> (external nets of the reference)
        ports, pnum = {}, 0
        tels = []
        for c in core:
            cell = C[c]
            tnp = {}
            for role, p, nn in G.inp[c]:
                d = G.driver(nn)
                if d in eid:
                    t = '%s.%s' % (eid[d], nn.rsplit('.', 1)[1])
                else:
                    if nn not in ports:
                        ports[nn] = 'p%d' % pnum; pnum += 1
                    t = ports[nn]
                tnp[p] = t
            # logical cfg: the most common one over the members (INIT: the reference's, the
            # others are regenerated through their pin permutation)
            votes = collections.Counter()
            for j in order:
                mc_ = maps[j][c]
                votes[json.dumps({kk: v for kk, v in C[mc_]['cfg'].items() if kk not in PHYS_KEYS and kk != 'INIT'
                                  and shared_owner(mc_, kk) is None}, sort_keys=True)] += 1
            tcfg = json.loads(votes.most_common(1)[0][0])
            if 'INIT' in cell['cfg']:
                tcfg['INIT'] = cell['cfg']['INIT']
            tels.append({'id': eid[c], 'kind': kind(cell), 'type': cell['type'], 'cfg': tcfg,
                         'tnet_of_pin': tnp, 'ref_cell': c})
        templates[fname] = {'signature': repr(k), 'reference': 0, 'elements': tels,
                            'ports': [{'id': p, 'ref_net': n, 'global': n in glob} for n, p in sorted(ports.items(), key=lambda kv: int(kv[1][1:]))],
                            'members': []}
        for inst_no, j in enumerate(order):
            mp = maps[j]
            cells = {eid[c]: mp[c] for c in core}
            # bindings
            bind = {}
            for tel in tels:
                mc = cells[tel['id']]
                for o, dd in C[mc]['dirs'].items():
                    if dd == 'out':
                        bind['%s.%s' % (tel['id'], o)] = '%s.%s' % (mc, o)
            # fixed-pin ports first
            for tel in tels:
                mc = cells[tel['id']]
                for p, t in tel['tnet_of_pin'].items():
                    if t.startswith('p') and p not in LUTP:
                        bind.setdefault(t, C[mc]['pins'].get(p))
            # LUT pin ports: search, fewest unknowns first
            pend = [tel for tel in tels if tel['kind'] in ('LUT', 'CCU2')]
            for _ in range(4):
                for tel in sorted(pend, key=lambda t: sum(1 for p, x in t['tnet_of_pin'].items() if p in LUTP and x not in bind)):
                    unk = sorted({x for p, x in tel['tnet_of_pin'].items() if p in LUTP and x not in bind})
                    if not unk:
                        continue
                    mc = cells[tel['id']]
                    known = {bind[x] for p, x in tel['tnet_of_pin'].items() if p in LUTP and x in bind}
                    cand = sorted({C[mc]['pins'][q] for q in LUTP if q in C[mc]['pins']} - known)
                    if len(unk) > len(cand):
                        continue
                    want = init_int(C[mc]['cfg'].get('INIT', '0' * 16))
                    for assign in itertools.permutations(cand, len(unk)):
                        b2 = dict(bind); b2.update(zip(unk, assign))
                        pi = lut_pi(tel, C[mc], b2, tel['tnet_of_pin'])
                        if pi is not None and perm_init(init_int(tel['cfg']['INIT']), pi) == want:
                            bind.update(zip(unk, assign)); break
            # placement + generation check
            placement, devs = {}, []
            for tel in tels:
                mc = cells[tel['id']]
                cell = C[mc]
                pl = {'cell': mc, 'pins': cell['pins'], 'dirs': cell['dirs'], 'cfgtile': cell_tile(cell)}
                if cell['type'] != tel['type']:
                    pl['type'] = cell['type']     # site type (e.g. TIOLOGIC vs IOLOGIC): physical
                for kk in ('bel', 'x', 'y', 'z', 'tile', 'unknown_bits'):
                    if kk in cell:
                        pl[kk] = cell[kk]
                phys = {kk: cell['cfg'][kk] for kk in PHYS_KEYS if kk in cell['cfg'] and shared_owner(mc, kk) is None}
                if phys:
                    pl['phys'] = phys
                sh = sorted(kk for kk in cell['cfg'] if shared_owner(mc, kk) is not None)
                if sh:
                    pl['shared'] = sh
                placement[tel['id']] = pl
                g = gen_cell(tel, pl, bind, C)
                if g is None or json.dumps(g, sort_keys=True) != json.dumps(cell, sort_keys=True):
                    if g is None:
                        why = 'no encoder / pin permutation'
                    else:
                        why = ','.join(sorted(kk for kk in set(g) | set(cell) if g.get(kk) != cell.get(kk)))
                        if g.get('cfg') != cell.get('cfg'):
                            why += ' [%s]' % ' '.join('%s=%s/%s' % (kk, g['cfg'].get(kk), cell['cfg'].get(kk))
                                                       for kk in sorted(set(g['cfg']) | set(cell['cfg']))
                                                       if g['cfg'].get(kk) != cell['cfg'].get(kk))
                    devs.append({'element': tel['id'], 'cell': mc, 'differs': why, 'raw': cell})
            mset = set(cells.values())
            nets = {n: net['nets'][n] for n in net['nets'] if G.driver(n) in mset}
            name = '%s__%d' % (fname, inst_no)
            instances.append({'name': name, 'family': fname, 'seed_cells': sorted(seeds[idx[j]])[:3],
                              'grown': len(mems[j]), 'placement': placement,
                              'bind': {t: bind[t] for t in sorted(bind) if bind[t] is not None},
                              'nets': nets, 'deviations': devs})
            templates[fname]['members'].append(name)
            taken |= mset
    os.makedirs(os.path.join(outdir, 'inst'), exist_ok=True)
    for f in os.listdir(os.path.join(outdir, 'inst')):
        os.remove(os.path.join(outdir, 'inst', f))
    owned_nets = set()
    for ins in instances:
        owned_nets |= set(ins['nets'])
        json.dump(ins, open(os.path.join(outdir, 'inst', ins['name'] + '.json'), 'w'), indent=1, sort_keys=True)
    rem = {k: v for k, v in net.items() if k not in ('cells', 'nets')}
    rem['cells'] = {c: v for c, v in net['cells'].items() if c not in taken}
    rem['nets'] = {n: v for n, v in net['nets'].items() if n not in owned_nets}
    json.dump(rem, open(os.path.join(outdir, 'remainder.json'), 'w'), indent=1, sort_keys=True)
    json.dump({'format': 'xo3-l6-1', 'families': templates}, open(os.path.join(outdir, 'template.json'), 'w'), indent=1, sort_keys=True)
    # reports
    R = []
    tot_cells = len(net['cells'])
    tot_lines = sum(len(c['config']) for c in net['cells'].values())
    gen_lines = sum(len(C[pl['cell']]['config']) for ins in instances for e, pl in ins['placement'].items()
                    if e not in {d['element'] for d in ins['deviations']})
    R.append('encoder check: %d of %d cells: config == encode(type, cfg, position, tile)' % (enc_ok, tot_cells))
    R.append('seeds: %d carry chains, %d IOL tiles; families with >= %d members: %d' % (
        len(ch), len(seeds) - len(ch), minfam, len(templates)))
    R.append('instance cells: %d of %d; config lines generated from templates: %d of %d (%.1f%%)' % (
        len(taken), tot_cells, gen_lines, tot_lines, 100.0 * gen_lines / max(1, tot_lines)))
    R.append('')
    R.append('%-10s %-14s %6s %6s %6s %6s %5s  %s' % ('family', 'instance', 'grown', 'templ', 'gen', 'cover', 'devs', 'seed'))
    for f, t in templates.items():
        R.append('# %s: %d elements (%s), %d ports (%d global); signature %s' % (
            f, len(t['elements']), dict(collections.Counter(e['kind'] for e in t['elements'])), len(t['ports']),
            sum(1 for p in t['ports'] if p['global']), t['signature'][:90]))
        for nm in t['members']:
            ins = next(i for i in instances if i['name'] == nm)
            ne = len(ins['placement']); nd = len(ins['deviations'])
            R.append('%-10s %-14s %6d %6d %6d %5.0f%% %5d  %s' % (f, nm, ins['grown'], ne, ne - nd,
                                                              100.0 * (ne - nd) / max(1, ins['grown']), nd, ins['seed_cells'][0]))
            for dv in ins['deviations']:
                R.append('    deviation %s %s: %s' % (dv['element'], dv['cell'], dv['differs']))
    # which instances talk to which (direct nets between their cells)
    where = {pl['cell']: ins['name'] for ins in instances for pl in ins['placement'].values()}
    adj = collections.defaultdict(collections.Counter)
    for c, lst in G.sinks.items():
        a_ = where.get(c)
        for sk, _ in lst:
            b_ = where.get(sk)
            if a_ and b_ and a_ != b_:
                adj[a_][b_] += 1
    R.append('')
    R.append('direct connections between instances (driver -> sink instance: nets):')
    for a_ in sorted(adj):
        R.append('  %s -> %s' % (a_, ', '.join('%s:%d' % kv for kv in sorted(adj[a_].items()))))
    open(os.path.join(outdir, 'report.txt'), 'w').write('\n'.join(R) + '\n')
    I = []
    for ins in instances:
        t = templates[ins['family']]
        I.append('## %s (family %s, %d template elements, %d deviations)' % (ins['name'], ins['family'], len(ins['placement']), len(ins['deviations'])))
        for e in t['elements']:
            I.append('  %-5s %-5s %s' % (e['id'], e['kind'], ins['placement'][e['id']]['cell']))
        for p in t['ports']:
            I.append('  port %-5s <- %s%s' % (p['id'], ins['bind'].get(p['id'], '?'), '  (global)' if p['global'] else ''))
    open(os.path.join(outdir, 'instances.txt'), 'w').write('\n'.join(I) + '\n')
    print('\n'.join(R[:3]))


def rebuild(outdir):
    rem = json.load(open(os.path.join(outdir, 'remainder.json')))
    tpl = json.load(open(os.path.join(outdir, 'template.json')))['families']
    out = {k: v for k, v in rem.items()}
    cells, nets = dict(rem['cells']), dict(rem['nets'])
    todo = []
    for f in sorted(os.listdir(os.path.join(outdir, 'inst'))):
        ins = json.load(open(os.path.join(outdir, 'inst', f)))
        T = {e['id']: e for e in tpl[ins['family']]['elements']}
        dev = {d['element']: d for d in ins['deviations']}
        for e, pl in ins['placement'].items():
            if e in dev:
                cells[pl['cell']] = dev[e]['raw']
            else:
                todo.append((bool(pl.get('shared')), ins['name'], T[e], pl, ins['bind']))
        nets.update(ins['nets'])
    for _, nm, tel, pl, bind in sorted(todo, key=lambda t: t[0]):   # slice owners first
        g = gen_cell(tel, pl, bind, cells)
        if g is None:
            raise SystemExit('cannot regenerate %s %s' % (nm, tel['id']))
        cells[pl['cell']] = g
    out['cells'], out['nets'] = cells, nets
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('op', choices=['extract', 'rebuild'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--rounds', type=int, default=8)
    ap.add_argument('--min-family', type=int, default=2)
    ap.add_argument('--iol-merge', action='store_true', help='one IOL family regardless of the number of TS registers')
    ap.add_argument('--max-hop', type=int, default=40, help='IOL families: propagation depth (edges) from the pads')
    a = ap.parse_args()
    if a.op == 'extract':
        extract(json.load(open(a.args[0])), a.args[1], a.rounds, a.min_family, a.max_hop, a.iol_merge)
    else:
        json.dump(rebuild(a.args[0]), open(a.args[1], 'w'), indent=1, sort_keys=True)


if __name__ == '__main__':
    main()
