#!/usr/bin/env python3
"""ai-re-metrics: single-node VictoriaMetrics for lab devices, run as a user service.

  ai-re-metrics start | stop | restart | status
  ai-re-metrics target add NAME HOST:PORT [--path /metrics] [--interval 15s] [--label k=v ...]
  ai-re-metrics target rm NAME
  ai-re-metrics target ls
  ai-re-metrics query 'PROMQL'          # instant query, prints result rows
  ai-re-metrics range 'PROMQL' [--since 1h] [--step 60s]   # min/avg/max per series
  ai-re-metrics url

Targets are files in the targets directory (one per NAME, file_sd format);
VictoriaMetrics re-reads them every 10 s, so adding or removing a target needs
no restart. Everything (data, targets, generated scrape config) lives under
$AI_RE_METRICS_DIR (default ~/.local/state/ai_re-metrics), never in the repo:
targets carry addresses. Listens on 127.0.0.1:8428 only.
"""
import argparse, json, os, re, shutil, subprocess, sys, time, urllib.parse, urllib.request
from pathlib import Path

UNIT = "ai-re-victoriametrics"
LISTEN = os.environ.get("AI_RE_METRICS_LISTEN", "127.0.0.1:8428")
BASE = Path(os.environ.get("AI_RE_METRICS_DIR", Path.home() / ".local/state/ai_re-metrics"))
TARGETS, DATA, SCRAPE = BASE / "targets", BASE / "data", BASE / "scrape.yaml"
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_.-]{0,62}$")


def env():
    e = dict(os.environ)
    e.setdefault("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    return e


def systemctl(*args, check=False):
    return subprocess.run(["systemctl", "--user", *args], env=env(), capture_output=True, text=True, check=check)


def write_scrape():
    BASE.mkdir(parents=True, exist_ok=True); TARGETS.mkdir(exist_ok=True)
    # One job reading every target file; each file sets its own job name,
    # metrics path and interval through __meta-free target labels.
    SCRAPE.write_text(f"""# generated by ai-re-metrics; edit targets with "ai-re-metrics target ..."
global:
  scrape_interval: 15s
  scrape_timeout: 10s
scrape_configs:
  - job_name: ai_re
    file_sd_configs:
      - files: ["{TARGETS}/*.json"]
    relabel_configs:
      - source_labels: [ai_re_job]
        target_label: job
      - source_labels: [ai_re_path]
        target_label: __metrics_path__
      - source_labels: [ai_re_interval]
        target_label: __scrape_interval__
      - regex: "ai_re_(job|path|interval)"
        action: labeldrop
""")


def cmd_start(a):
    write_scrape(); DATA.mkdir(parents=True, exist_ok=True)
    if systemctl("is-active", UNIT).stdout.strip() == "active":
        print(f"{UNIT} already running on {LISTEN}"); return
    systemctl("reset-failed", UNIT)
    vm = shutil.which("victoria-metrics")
    if not vm:
        sys.exit("victoria-metrics not on PATH: run inside the ai_re devshell (nix develop)")
    vm = os.path.realpath(vm)
    r = subprocess.run(["systemd-run", "--user", f"--unit={UNIT}", "--description=ai_re VictoriaMetrics",
                        "--property=Restart=always", "--property=RestartSec=5",
                        vm, f"-storageDataPath={DATA}", "-retentionPeriod=180d", f"-httpListenAddr={LISTEN}",
                        f"-promscrape.config={SCRAPE}", "-promscrape.configCheckInterval=10s",
                        "-promscrape.fileSDCheckInterval=10s", "-loggerLevel=WARN"],
                       env=env(), capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr.strip())
    for _ in range(30):
        try:
            urllib.request.urlopen(f"http://{LISTEN}/health", timeout=1); break
        except OSError:
            time.sleep(0.5)
    else:
        sys.exit(f"{UNIT} did not come up; see: journalctl --user -u {UNIT}")
    print(f"{UNIT} running on http://{LISTEN} (data {DATA})")


def cmd_stop(a):
    systemctl("stop", UNIT); print(f"{UNIT} stopped")


def cmd_status(a):
    st = systemctl("is-active", UNIT).stdout.strip()
    print(f"service: {st}  url: http://{LISTEN}  dir: {BASE}")
    if st == "active":
        try:
            d = json.load(urllib.request.urlopen(f"http://{LISTEN}/api/v1/targets", timeout=5))
            for t in d["data"]["activeTargets"]:
                print(f"  {t['labels'].get('job','?'):20} {t['scrapeUrl']:45} {t['health']:5} "
                      f"last {t.get('lastScrape','')[:19]} {t.get('lastError','')}")
        except OSError as e:
            print(f"  targets: {e}")


def cmd_target(a):
    TARGETS.mkdir(parents=True, exist_ok=True)
    if a.action == "ls":
        for f in sorted(TARGETS.glob("*.json")):
            g = json.loads(f.read_text())[0]
            print(f"{f.stem:20} {', '.join(g['targets'])}  {g['labels'].get('ai_re_path','/metrics')}  "
                  f"{g['labels'].get('ai_re_interval','15s')}  "
                  + " ".join(f"{k}={v}" for k, v in g["labels"].items() if not k.startswith("ai_re_")))
        return
    if not NAME_RE.match(a.name):
        sys.exit("NAME: lowercase letters, digits, _ . - (it becomes the job label)")
    f = TARGETS / f"{a.name}.json"
    if a.action == "rm":
        if f.exists():
            f.unlink(); print(f"removed {a.name}")
        else:
            sys.exit(f"no target {a.name}")
        return
    labels = {"ai_re_job": a.name, "ai_re_path": a.path, "ai_re_interval": a.interval}
    for kv in a.label or []:
        k, _, v = kv.partition("=")
        if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", k) or k.startswith("__") or k.startswith("ai_re_"):
            sys.exit(f"bad label {kv!r}")
        labels[k] = v
    existed = f.exists()
    tmp = f.with_suffix(".tmp")
    tmp.write_text(json.dumps([{"targets": [a.address], "labels": labels}], indent=1) + "\n")
    tmp.replace(f)
    print(f"{'updated' if existed else 'added'} {a.name} -> {a.address}{a.path} every {a.interval} (picked up within ~10 s)")


def api(path, params):
    q = urllib.parse.urlencode(params)
    return json.load(urllib.request.urlopen(f"http://{LISTEN}{path}?{q}", timeout=30))


def fmt_metric(m):
    name = m.get("__name__", "")
    rest = ",".join(f'{k}="{v}"' for k, v in sorted(m.items()) if k != "__name__")
    return f"{name}{{{rest}}}"


def cmd_query(a):
    d = api("/api/v1/query", {"query": a.promql})
    for r in d["data"]["result"]:
        print(f"{fmt_metric(r['metric'])} {r['value'][1]}")


def cmd_range(a):
    end = time.time()
    unit = {"s": 1, "m": 60, "h": 3600, "d": 86400}
    since = int(a.since[:-1]) * unit[a.since[-1]]
    d = api("/api/v1/query_range", {"query": a.promql, "start": end - since, "end": end, "step": a.step})
    for r in d["data"]["result"]:
        v = [float(x[1]) for x in r["values"]]
        if v:
            print(f"{fmt_metric(r['metric'])} n={len(v)} min={min(v):.2f} avg={sum(v)/len(v):.2f} max={max(v):.2f} last={v[-1]:.2f}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for c in ("start", "stop", "status", "url"):
        sub.add_parser(c)
    sub.add_parser("restart")
    t = sub.add_parser("target"); ts = t.add_subparsers(dest="action", required=True)
    ad = ts.add_parser("add"); ad.add_argument("name"); ad.add_argument("address")
    ad.add_argument("--path", default="/metrics"); ad.add_argument("--interval", default="15s")
    ad.add_argument("--label", action="append")
    rm = ts.add_parser("rm"); rm.add_argument("name")
    ts.add_parser("ls")
    q = sub.add_parser("query"); q.add_argument("promql")
    r = sub.add_parser("range"); r.add_argument("promql"); r.add_argument("--since", default="1h"); r.add_argument("--step", default="60s")
    a = ap.parse_args()
    if a.cmd == "url":
        print(f"http://{LISTEN}"); return
    if a.cmd == "restart":
        cmd_stop(a); cmd_start(a); return
    {"start": cmd_start, "stop": cmd_stop, "status": cmd_status, "target": cmd_target,
     "query": cmd_query, "range": cmd_range}[a.cmd](a)


if __name__ == "__main__":
    try:
        main()
    except urllib.error.URLError as e:
        sys.exit(f"ai-re-metrics: VictoriaMetrics not reachable at {LISTEN} ({e.reason}); try: ai-re-metrics start")
