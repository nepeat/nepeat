#! @bash@/bin/sh -e
# CS8210 U-Boot bootmenu builder, adapted from dmc12-nixos/uboot-menu.
# Invoked by NixOS activation as `installBootLoader <toplevel>`, and by the
# disk image build with CS8210_BOOT_TARGET pointing into the image tree.
#
# Stages each generation's kernel + initrd + DTB into <target>/nixos/ and
# writes <target>/u-boot.menu (bootmenu_N entries for `env import -t`) plus
# the static <target>/boot.scr that loads the menu.
#
# Stock U-Boot 2018.05-alpine_db quirks this works around:
#   * booti/sysboot only accept a mkimage-wrapped ramdisk (no raw addr:size),
#     so the initrd is wrapped as a legacy uImage with compression "none".
#   * The kernel is a raw arm64 Image booted with `booti` in place. A gzip
#     uImage + bootm would have to decompress to a 2 MiB aligned address that
#     either overlaps U-Boot (ends at 0x04000000) or the compressed copy.
shopt -s nullglob

export PATH=/empty:@path@

default="${1:-}"
if [ -z "$default" ]; then
    echo "usage: $0 <toplevel>" >&2
    exit 1
fi

target="${CS8210_BOOT_TARGET:-/boot}"
profiles="${CS8210_PROFILES_DIR:-/nix/var/nix/profiles}"
timeout=@timeout@
numGenerations=@numGenerations@
dtbName=@dtbName@
bootDev="@bootDev@"       # U-Boot device spec, e.g. "scsi 0:2"
bootPrefix="@bootPrefix@" # where <target> is as seen by U-Boot, e.g. "/boot"

kernelAddr=@kernelAddr@
initrdAddr=@initrdAddr@
fdtAddr=@fdtAddr@

mkdir -p "$target/nixos"

# /nix/store/<hash>-<name>/file -> <hash>-<name>-<file>
cleanName() {
    echo "$1" | sed 's|^/nix/store/||' | sed 's|/|-|g'
}

declare -A filesCopied

copyToKernelsDir() {
    local src
    src=$(readlink -f "$1")
    local dst="$target/nixos/$(cleanName "$src")"
    if ! test -e "$dst"; then
        local dstTmp="$dst.tmp.$$"
        cp "$src" "$dstTmp"
        mv "$dstTmp" "$dst"
    fi
    filesCopied[$dst]=1
    result=$dst
}

stageInitrd() {
    local src
    src=$(readlink -f "$1")
    local dst="$target/nixos/$(cleanName "$src").uImage"
    if ! test -e "$dst"; then
        local dstTmp="$dst.tmp.$$"
        # -C none: the kernel, not U-Boot, decompresses the cpio.
        mkimage -A arm64 -O linux -T ramdisk -C none \
            -n "CS8210 NixOS initrd" \
            -d "$src" "$dstTmp" > /dev/null
        mv "$dstTmp" "$dst"
    fi
    filesCopied[$dst]=1
    result=$dst
}

# One `bootmenu_N=label=cmd` line per generation; bootmenu_0 is the default.
addEntry() {
    local path
    path=$(readlink -f "$1")
    local tag="$2"
    local idx="$3"

    if ! test -e "$path/kernel" -a -e "$path/initrd"; then
        return
    fi

    copyToKernelsDir "$path/kernel";           local kernel; kernel=$(basename "$result")
    stageInitrd      "$path/initrd";           local initrd; initrd=$(basename "$result")
    copyToKernelsDir "$path/dtbs/$dtbName";    local dtb;    dtb=$(basename "$result")

    local timestamp
    timestamp=$(date "+%Y-%m-%d %H:%M" -d @"$(stat -L -c '%Z' "$path")")
    local nixosLabel
    nixosLabel=$(cat "$path/nixos-version")
    local extraParams
    extraParams=$(cat "$path/kernel-params")

    local label
    if [ "$tag" = "default" ]; then
        label="NixOS - Default ($timestamp - $nixosLabel)"
    else
        label="NixOS - Gen $tag ($timestamp - $nixosLabel)"
    fi

    local cmd
    cmd="ext4load $bootDev $kernelAddr $bootPrefix/nixos/$kernel"
    cmd="$cmd; ext4load $bootDev $initrdAddr $bootPrefix/nixos/$initrd"
    cmd="$cmd; ext4load $bootDev $fdtAddr $bootPrefix/nixos/$dtb"
    cmd="$cmd; setenv bootargs 'init=$path/init $extraParams'"
    cmd="$cmd; booti $kernelAddr $initrdAddr $fdtAddr"

    printf 'bootmenu_%d=%s=%s\n' "$idx" "$label" "$cmd"
}

tmpFile="$target/u-boot.menu.tmp.$$"
{
    echo "# Auto-generated by NixOS cs8210-uboot-menu -- do not edit."
    echo "bootmenu_delay=$timeout"
    addEntry "$default" default 0
    idx=1
    if [ "$numGenerations" -gt 0 ] && [ -d "$profiles" ]; then
        for generation in $(
                (cd "$profiles" && ls -d system-*-link) \
                | sed 's/system-\([0-9]\+\)-link/\1/' \
                | sort -n -r \
                | head -n "$numGenerations"); do
            link="$profiles/system-$generation-link"
            if [ "$(readlink -f "$link")" = "$(readlink -f "$default")" ]; then
                continue
            fi
            addEntry "$link" "$generation" "$idx"
            idx=$((idx + 1))
        done
    fi
} > "$tmpFile"

mv -f "$tmpFile" "$target/u-boot.menu"

cp -f @bootScr@ "$target/boot.scr.tmp.$$"
chmod 0644 "$target/boot.scr.tmp.$$"
mv -f "$target/boot.scr.tmp.$$" "$target/boot.scr"

# Drop staged files no remaining generation references.
for fn in "$target/nixos"/*; do
    if ! test "${filesCopied[$fn]}" = 1; then
        echo "[cs8210-uboot-menu] removing stale boot file: $fn"
        chmod +w -- "$fn"
        rm -rf -- "$fn"
    fi
done
