import contextlib
import csv
import hashlib
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from devicehunt import specifications
from devicehunt import __main__ as cli
from devicehunt.catalog import Catalog

DEFAULT_OUTPUTS = json.loads(
    (Path(__file__).parent / 'fixtures' / 'specification-grouping-defaults.json').read_text())


class GroupingTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.path = Path(self.tmp.name) / 'fixture.sqlite'
        self.c = Catalog(self.path)
        self.sources = set()

    def tearDown(self):
        self.c.db.close()
        self.tmp.cleanup()

    def add(self, sid, key, facts, affiliations=(('Celestica', 'documentation_vendor'),),
            identifiers=(), brand='Celestica', model='DS4000', revision=''):
        if sid not in self.sources:
            self.c.source(sid, 'https://example.invalid/' + sid, 'vendor' if sid != 'b' else 'community', 'fixture', 'fixture')
            self.sources.add(sid)
        self.c.add(sid, key, 'https://example.invalid/' + sid + '/' + key, brand, model,
                   brand + ' ' + model, 'switch', {}, affiliations, identifiers, facts, revision=revision)
        self.c.finish(sid, 1)

    def groups(self, query='DS4000', **kwargs):
        return specifications.search(self.c, query, limit=-1, group_identical=True, **kwargs)

    def capture(self, module, args):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(module.main(['--db', str(self.path), 'specs', *args]), 0)
        return out.getvalue()

    def test_unflagged_api_and_all_cli_formats_are_byte_identical(self):
        for sid in ('a', 'b'):
            self.add(sid, 'one', [('power_description', '2 PSUs'), ('spec_power_supply', '2 x 800 W')],
                     identifiers=[('part_number', 'P-1'), ('alias', 'alias')])
        # These snapshots were captured from the original ungrouped modules;
        # they are not regenerated by this test or derived from the new path.
        for case in DEFAULT_OUTPUTS['cases']:
            query, kwargs = case['query'], case['kwargs']
            self.assertEqual(case['api_rows'],
                             specifications.search(self.c, query, limit=-1, group_identical=False, **kwargs))
            self.assertEqual(case['api_rows'], specifications.search(self.c, query, limit=-1, **kwargs))
            for fmt in ('json', 'csv', 'table'):
                self.assertEqual(case['cli'][fmt], self.capture(cli, case['args'] + ['--format', fmt]))
        self.assertEqual(DEFAULT_OUTPUTS['default_api_rows'], specifications.search(self.c, 'DS4000'))

    def test_full_duplicate_evidence_across_and_within_sources(self):
        facts = [('spec_power_supply', '2 x 800 W')]
        self.add('a', 'one', facts)
        self.add('a', 'two', facts, affiliations=[('Celestica', 'reported_system_vendor')])
        self.add('b', 'one', facts, affiliations=[('Oracle', 'documentation_vendor')])
        group, = self.groups(include_source_facts=True)
        self.assertEqual((group['evidence_count'], group['record_count'], group['source_count']), (3, 3, 2))
        self.assertEqual(len(specifications.search(self.c, 'DS4000', include_source_facts=True, limit=-1)), 2)
        self.assertEqual({r['source_url'] for r in group['evidence']},
                         {'https://example.invalid/a/one', 'https://example.invalid/a/two', 'https://example.invalid/b/one'})
        self.assertEqual({r['source_key'] for r in group['evidence']}, {'one', 'two'})
        self.assertEqual({a['role'] for r in group['evidence'] for a in r['affiliations']},
                         {'documentation_vendor', 'reported_system_vendor'})
        self.assertNotIn('source_url', group)
        self.assertTrue(all(r['raw_fact'] == {'name': 'spec_power_supply', 'value': '2 x 800 W'} for r in group['evidence']))
        self.assertEqual(group, self.groups(include_source_facts=True)[0])

    def test_alias_and_part_select_later_duplicate_before_grouping(self):
        self.add('a', 'one', [('spec_power_supply', 'same')])
        self.add('a', 'two', [('spec_power_supply', 'same')])
        flat = specifications.search(self.c, 'DS4000', include_source_facts=True, limit=-1)
        dropped = next(r['id'] for r in self.c.db.execute('SELECT id FROM records') if r['id'] != flat[0]['record_id'])
        self.c.db.executemany('INSERT INTO identifiers VALUES (?,?,?)',
                             [(dropped, 'alias', 'Straße_100%'), (dropped, 'part_number', 'Straße_100%')])
        self.c.db.commit()
        for mode in ('exact_model', 'exact_part_number'):
            group, = self.groups(' STRASSE_100% ', include_source_facts=True, **{mode: True})
            self.assertEqual([r['record_id'] for r in group['evidence']], [dropped])
            if mode == 'exact_part_number':
                self.assertEqual(group['evidence'][0]['matched_part_numbers'], ['Straße_100%'])
            self.assertEqual(self.groups('STRASSE_100%-X', include_source_facts=True, **{mode: True}), [])
        self.assertEqual(specifications.search(self.c, 'Straße_100%', exact_model=True, include_source_facts=True), [])

    def test_vendor_cannot_borrow_sibling_role_or_alias(self):
        self.add('a', 'one', [('power_description', 'same')])
        self.add('b', 'one', [('power_description', 'same')], affiliations=[('Oracle', 'documentation_vendor')],
                 identifiers=[('alias', 'only-b'), ('part_number', 'only-b')])
        for mode in ('exact_model', 'exact_part_number'):
            self.assertEqual(self.groups('only-b', target='Celestica', **{mode: True}), [])
            group, = self.groups('only-b', target='Oracle', **{mode: True})
            self.assertEqual([r['source_id'] for r in group['evidence']], ['b'])
            self.assertEqual(group['evidence'][0]['affiliations'],
                             [{'company': 'Oracle', 'target': 'Oracle', 'role': 'documentation_vendor'}])

    def test_strict_device_revision_origin_field_raw_and_conflict_boundaries(self):
        display = specifications.source_fact_statement('spec_power_supply', 'same')
        facts = [('power_description', display), ('spec_power_supply', 'same'),
                 ('psu_configuration_1', '2 x 800W'), ('psu_configuration_2', '2 x 800W'),
                 ('psu_rated_output_raw', '800W'), ('psu_rated_output_raw', '800 W'),
                 ('dmi_chassis_type', 'Rack Mount Chassis (a/0123456789ab:1)'),
                 ('dmi_chassis_type', 'Rack Mount Chassis (b/0123456789ab:2)'),
                 ('power_description', 'contradictory 3 PSUs')]
        self.add('a', 'one', facts)
        self.add('a', 'two', [('power_description', display)], brand='Oracle')
        self.add('a', 'three', [('power_description', display)], revision='R2')
        groups = self.groups(include_source_facts=True)
        self.assertEqual(len(groups), 11)
        self.assertEqual(len({g['device_id'] for g in groups}), 3)
        dmi = [g for g in groups if g['source_fact_name'] == 'dmi_chassis_type']
        self.assertEqual(len(dmi), 2)
        self.assertEqual(dmi[0]['statement'], dmi[1]['statement'])
        self.assertNotEqual(dmi[0]['evidence'][0]['raw_fact']['value'], dmi[1]['evidence'][0]['raw_fact']['value'])
        overlap = [g for g in groups if g['statement'] == display and g['revision'] == '' and g['brand'] == 'Celestica']
        self.assertEqual({g['origin'] for g in overlap}, {'curated statement', 'source fact'})

    def test_placeholders_and_whitelist_keep_existing_meaning(self):
        self.add('a', 'one', [('spec_power_supply', 'unknown'), ('power', '800W'),
                             ('netbox_u_height', '2'), ('power_description', 'unknown')])
        groups = self.groups(include_source_facts=True)
        self.assertEqual({g['origin'] for g in groups}, {'curated statement', 'source fact'})
        self.assertEqual({g['source_fact_name'] for g in groups}, {'', 'netbox_u_height'})
        self.assertEqual(len(self.groups()), 1)

    def test_complete_groups_precede_limit_and_keep_traversal_order(self):
        for sid, values in [('a', ['first', 'second']), ('b', ['third']), ('z', ['first'])]:
            self.add(sid, 'one', [('power_description', v) for v in values])
        full = self.groups()
        limited = specifications.search(self.c, 'DS4000', limit=1, group_identical=True)
        self.assertEqual(limited, full[:1])
        self.assertEqual([g['statement'] for g in full], ['first', 'second', 'third'])
        self.assertEqual([r['source_id'] for r in limited[0]['evidence']], ['a', 'z'])
        self.assertEqual(specifications.search(self.c, 'DS4000', limit=0, group_identical=True), [])
        expected = specifications.curated_statement_rows(self.c)
        members = [r for g in full for r in g['evidence']]
        self.assertEqual(sorted((r['record_id'], r['category'], r['statement']) for r in members),
                         sorted((r['record_id'], r['category'], r['statement']) for r in expected))

    def test_validation_and_literal_model_space_suffix(self):
        self.add('a', 'one', [('power_description', 'literal')], model='A  B-01')
        self.assertEqual(len(self.groups(' a  b-01 ', exact_model=True)), 1)
        for query in ('A B-01', 'A  B-01-X'):
            self.assertEqual(self.groups(query, exact_model=True), [])
        for kwargs in ({'limit': -2}, {'exact_model': True, 'exact_part_number': True},
                       {'exact_model': True, 'query': ''}, {'exact_part_number': True, 'query': ''},
                       {'target': 'unknown-vendor'}):
            args = {'query': 'DS4000', 'group_identical': True} | kwargs
            with self.assertRaises(ValueError): specifications.search(self.c, **args)

    def test_json_csv_members_and_table_provenance(self):
        for sid in ('a', 'b'):
            self.add(sid, 'one', [('power_description', 'unique shared statement')],
                     identifiers=[('part_number', 'PN-1')])
        args = ['PN-1', '--exact-part-number', '--group-identical', '--limit', '-1']
        groups = json.loads(self.capture(cli, args + ['--format', 'json']))
        csv_rows = list(csv.DictReader(io.StringIO(self.capture(cli, args + ['--format', 'csv']))))
        self.assertEqual(json.loads(csv_rows[0]['evidence_json']), groups[0]['evidence'])
        self.assertNotIn('evidence', csv_rows[0])
        table = self.capture(cli, args + ['--format', 'table'])
        self.assertEqual(table.count('unique shared statement'), 1)
        for member in groups[0]['evidence']:
            for field in ('record_id', 'source_id', 'source_url', 'tier', 'source_key'):
                self.assertIn(json.dumps(member[field]), table)
        self.assertEqual(table.count('  evidence '), 2)
        self.assertIn('matched_part_numbers', table)

    def test_empty_output_conventions_and_missing_database(self):
        for fmt, expected in [('json', '[]\n'), ('csv', ''), ('table', 'No matching records.\n')]:
            self.assertEqual(self.capture(cli, ['missing', '--group-identical', '--format', fmt]), expected)
        missing = Path(self.tmp.name) / 'missing.sqlite'
        with self.assertRaises(Exception): Catalog(missing, read_only=True)
        self.assertFalse(missing.exists())

    def test_table_preserves_raw_values_when_displayed_statements_match(self):
        raw_values = ['Rack Mount Chassis (a/0123456789ab:1)',
                      'Rack Mount Chassis (b/0123456789ab:2)']
        # One record and URL: neither provenance nor displayed text can stand
        # in for the raw fact that distinguishes these two strict groups.
        self.add('a', 'one', [('dmi_chassis_type', value) for value in raw_values])
        args = ['DS4000', '--exact-model', '--include-source-facts', '--group-identical', '--limit', '-1']
        groups = json.loads(self.capture(cli, args + ['--format', 'json']))
        self.assertEqual(len(groups), 2)
        self.assertEqual(groups[0]['statement'], groups[1]['statement'])
        self.assertEqual(groups[0]['evidence'][0]['record_id'], groups[1]['evidence'][0]['record_id'])
        table = self.capture(cli, args + ['--format', 'table'])
        headers = [json.loads(line) for line in table.splitlines() if not line.startswith('  evidence ')]
        self.assertEqual({row['raw_fact']['value'] for row in headers}, set(raw_values))
        self.assertEqual({row['raw_fact']['name'] for row in headers}, {'dmi_chassis_type'})
        self.assertNotEqual(headers[0], headers[1])
        for value in raw_values:
            self.assertEqual(table.count(value), 1)
        self.assertEqual(table.count('  evidence '), 2)

    def test_bulk_queries_read_only_transaction_and_no_external_calls(self):
        self.add('a', 'one', [('spec_power_supply', 'same')])
        queries = []
        self.c.db.set_trace_callback(queries.append)
        with patch('urllib.request.urlopen', side_effect=AssertionError('network')), \
             patch('subprocess.run', side_effect=AssertionError('process')), \
             patch('subprocess.Popen', side_effect=AssertionError('process')):
            self.groups(exact_model=True, include_source_facts=True)
        one_count = len(queries)
        self.c.db.set_trace_callback(None)
        for n in range(20): self.add('a', str(n), [('spec_power_supply', 'same')])
        before = hashlib.sha256(self.path.read_bytes()).hexdigest()
        self.c.db.execute('BEGIN')
        queries.clear(); self.c.db.set_trace_callback(queries.append)
        groups = self.groups(exact_model=True, include_source_facts=True)
        self.c.db.set_trace_callback(None)
        self.assertEqual(len(queries), one_count)
        self.assertTrue(all(q.lstrip().upper().startswith('SELECT') for q in queries))
        self.assertEqual(groups[0]['evidence_count'], 21)
        self.assertTrue(self.c.db.in_transaction)
        self.assertEqual(hashlib.sha256(self.path.read_bytes()).hexdigest(), before)
        self.c.db.rollback()


if __name__ == '__main__': unittest.main()
