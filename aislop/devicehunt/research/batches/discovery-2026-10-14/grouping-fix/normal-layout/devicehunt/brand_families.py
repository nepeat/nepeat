"""Reviewed brand-family table, used ONLY to group lookup / match-listing / model-collisions output.

Display-only by construction: nothing here changes a device id, an identity, a target, an
affiliation, a ranking, a row set or any count. `vendor-inventory`, `TARGETS` and importers never
import this module. A family says "these brand strings belong to one corporate group", with a
typed relation, dated first-party evidence (url + local capture path + sha256) and a reviewer. It
asserts nothing about which legal entity a catalog row means, who manufactured a unit, or that two
model strings are the same product.

File: data/brand-families.json (schema_version 1)
  families[]              id, name, group_entity, scope_note, members[]
  members[]               brand, relations[], evidence[], date, reviewer, review_status, note
  model_prefix_aliases    the generated own-brand model-prefix rule and its audit pair list

Brand strings are matched on catalog.normalize(brand) (lowercase alphanumerics), the same key the
catalog uses for identities, so `ORACLE` and `Oracle` resolve alike while `Sun Fire` stays unmapped.
review_status `pending` rows are displayed (they are flagged in every output's `brand_families`
metadata); `rejected` rows are ignored.

Model-prefix alias rule: exactly model_collisions.stripped_key (strip ONE leading token equal to the
member's own brand, or the first word of a multi-word brand). alias_key() is (normalised brand,
stripped key). The pair list stored in the file is generated by `regenerate-aliases` for audit;
the live rule is always the code, never the stored list.

Command line (read-only unless --write; --write only rewrites model_prefix_aliases):
  python3 -m devicehunt.brand_families check [--db data/devices.sqlite]
  python3 -m devicehunt.brand_families regenerate-aliases [--db ...] [--write]
"""
import argparse
import datetime as dt
import hashlib
import json
import re
import sqlite3
import sys
from pathlib import Path

from .catalog import normalize
from .model_collisions import EXCLUDED_KIND_WORDS, kind_excluded, plain_key, stripped_key

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PATH = ROOT / 'data/brand-families.json'
SCHEMA_VERSION = 1
RELATIONS = frozenset({'own_brand', 'subsidiary_brand', 'abbreviation', 'acquired_company', 'renamed', 'same_entity'})
REVIEW_STATUSES = frozenset({'pending', 'accepted', 'rejected'})
RULE = {
    'name': 'own_brand_leading_token',
    'source': 'devicehunt.model_collisions.stripped_key',
    'description': ('Casefold and collapse whitespace; strip ONE leading token equal to the member\'s own brand '
                    '(the whole brand string or the first word of a multi-word brand) followed by whitespace; '
                    'the remainder must be non-empty. Suffixes, hyphens, punctuation and revisions are never touched.'),
    'scope': 'same normalised brand only (catalog.normalize); never across brands',
    'skipped_kind_words': list(EXCLUDED_KIND_WORDS),
    'audit_note': ('The generated list is a same-brand audit list only. It includes pairs for brand strings the family table '
                   'deliberately does not map (Inspur Corporation, Inspur ... (IEI)); those imply no IEIT/Inspur relation. '
                   'No output consumes the aliases: there is no "also known as" display or alias lookup.'),
}
_SHA = re.compile(r'[0-9a-f]{64}')
_DATE = re.compile(r'\d{4}-\d{2}-\d{2}')


class FamilyFileError(ValueError):
    pass


def _fail(where, message):
    raise FamilyFileError('%s: %s' % (where, message))


def _text(value, where):
    if not isinstance(value, str) or not value.strip():
        _fail(where, 'must be a nonempty string')
    return value


def _date(value, where, allow_null=False):
    if value is None and allow_null:
        return
    if not isinstance(value, str) or not _DATE.fullmatch(value):
        _fail(where, 'must be an ISO date (YYYY-MM-DD)' + (' or null' if allow_null else ''))
    try:
        dt.date.fromisoformat(value)
    except ValueError:
        _fail(where, 'not a calendar date')


def _validate_evidence(item, where):
    if not isinstance(item, dict):
        _fail(where, 'evidence item must be an object')
    url = _text(item.get('url'), where + '.url')
    if not url.startswith(('http://', 'https://')) or re.search(r'\s', url):
        _fail(where + '.url', 'must be an http(s) URL without whitespace')
    _text(item.get('local_path'), where + '.local_path')
    if not isinstance(item.get('sha256'), str) or not _SHA.fullmatch(item['sha256']):
        _fail(where + '.sha256', 'must be 64 lowercase hex characters')
    _text(item.get('statement'), where + '.statement')
    _date(item.get('as_of'), where + '.as_of', allow_null=True)
    if item.get('as_of') is None:
        _text(item.get('date_note'), where + '.date_note (required when as_of is null)')
    _date(item.get('captured_on'), where + '.captured_on')


def _validate_member(member, where):
    if not isinstance(member, dict):
        _fail(where, 'member must be an object')
    _text(member.get('brand'), where + '.brand')
    if not normalize(member['brand']):
        _fail(where + '.brand', 'has no alphanumeric characters')
    relations = member.get('relations')
    if not isinstance(relations, list) or not relations:
        _fail(where + '.relations', 'must be a nonempty list')
    for relation in relations:
        if relation not in RELATIONS:
            _fail(where + '.relations', 'unknown relation %r (allowed: %s)' % (relation, ', '.join(sorted(RELATIONS))))
    evidence = member.get('evidence')
    if not isinstance(evidence, list) or not evidence:
        _fail(where + '.evidence', 'every row needs at least one evidence item')
    for i, item in enumerate(evidence):
        _validate_evidence(item, '%s.evidence[%d]' % (where, i))
    _date(member.get('date'), where + '.date')
    status = member.get('review_status')
    if status not in REVIEW_STATUSES:
        _fail(where + '.review_status', 'must be one of ' + ', '.join(sorted(REVIEW_STATUSES)))
    reviewer = member.get('reviewer', '<missing>')
    if reviewer == '<missing>':
        _fail(where + '.reviewer', 'key required (null until an independent reviewer signs)')
    if reviewer is not None:
        _text(reviewer, where + '.reviewer')
    if status == 'pending' and reviewer is not None:
        _fail(where, 'pending rows must have reviewer null')
    if status in ('accepted', 'rejected') and reviewer is None:
        _fail(where, status + ' rows need a named reviewer')
    if status == 'accepted':
        _date(member.get('reviewed_on'), where + '.reviewed_on')


class FamilyTable:
    def __init__(self, data, path, sha256):
        self.path = Path(path)
        self.sha256 = sha256
        self.data = data
        self.schema_version = data['schema_version']
        self.families = {}
        self._by_norm = {}
        self.rows_total = self.rows_pending = 0
        for fi, family in enumerate(data.get('families', ())):
            where = 'families[%d]' % fi
            if not isinstance(family, dict):
                _fail(where, 'must be an object')
            fid = _text(family.get('id'), where + '.id')
            if fid in self.families:
                _fail(where + '.id', 'duplicate family id ' + fid)
            _text(family.get('name'), where + '.name')
            _text(family.get('group_entity'), where + '.group_entity')
            members = family.get('members')
            if not isinstance(members, list) or not members:
                _fail(where + '.members', 'must be a nonempty list')
            self.families[fid] = family
            for mi, member in enumerate(members):
                mwhere = '%s.members[%d]' % (where, mi)
                _validate_member(member, mwhere)
                self.rows_total += 1
                self.rows_pending += member['review_status'] == 'pending'
                if member['review_status'] == 'rejected':
                    continue
                key = normalize(member['brand'])
                if key in self._by_norm:
                    _fail(mwhere + '.brand', 'brand %r already belongs to family %r' % (member['brand'], self._by_norm[key]))
                self._by_norm[key] = fid

    def family_of(self, brand):
        """Family id for a brand string, or None. Display grouping only."""
        return self._by_norm.get(normalize(brand)) if brand else None

    def members(self, family_id):
        return sorted(m['brand'] for m in self.families[family_id]['members'] if m['review_status'] != 'rejected')

    def metadata(self):
        return {'path': _display_path(self.path), 'sha256': self.sha256, 'schema_version': self.schema_version,
                'display_only': True, 'families': sorted(self.families), 'rows': self.rows_total,
                'rows_pending_review': self.rows_pending}


def _display_path(path):
    try:
        return str(Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def parse(raw, path='<memory>'):
    try:
        data = json.loads(raw)
    except ValueError as error:
        raise FamilyFileError('%s is not valid JSON: %s' % (path, error))
    if not isinstance(data, dict) or data.get('schema_version') != SCHEMA_VERSION:
        raise FamilyFileError('%s: schema_version must be %d' % (path, SCHEMA_VERSION))
    if not isinstance(data.get('families'), list):
        raise FamilyFileError('%s: families must be a list' % path)
    return FamilyTable(data, path, hashlib.sha256(raw if isinstance(raw, bytes) else raw.encode()).hexdigest())


def load(path):
    path = Path(path)
    return parse(path.read_bytes(), path)


def load_default():
    """The reviewed table, or None when the file is absent (outputs then carry no family keys)."""
    path = Path(DEFAULT_PATH)
    return load(path) if path.is_file() else None


_cache = {}


def default_table():
    path = Path(DEFAULT_PATH)
    if not path.is_file():
        return None
    stamp = (str(path), path.stat().st_mtime_ns)
    if stamp not in _cache:
        _cache.clear()
        _cache[stamp] = load(path)
    return _cache[stamp]


def family_of(brand, table=None):
    table = table or default_table()
    return table.family_of(brand) if table else None


def alias_key(brand, model):
    """(normalised brand, own-brand-stripped model key): the model-prefix alias rule, same brand only."""
    return normalize(brand), stripped_key(brand, model)[0]


# --- catalog-side checks (read-only) -------------------------------------------------------

def check_catalog(table, db):
    """Which member brands exist in the catalog. Returns {'present': {...}, 'missing': [...]}."""
    seen = {}
    for r in db.execute('SELECT brand,count(*) n FROM devices GROUP BY brand ORDER BY brand'):
        seen.setdefault(normalize(r[0]), []).append((r[0], r[1]))
    present, missing = {}, []
    for family in table.families.values():
        for member in family['members']:
            hits = seen.get(normalize(member['brand']))
            if hits:
                present[member['brand']] = {'catalog_strings': [h[0] for h in hits], 'identities': sum(h[1] for h in hits)}
            else:
                missing.append(member['brand'])
    return {'present': present, 'missing': missing}


def verify_evidence(table, root=ROOT):
    """Re-hash each local capture. Returns {'ok': n, 'absent': [...], 'mismatch': [...]}."""
    result = {'ok': 0, 'absent': [], 'mismatch': []}
    done = set()
    for family in table.families.values():
        for member in family['members']:
            for item in member['evidence']:
                key = (item['local_path'], item['sha256'])
                if key in done:
                    continue
                done.add(key)
                path = Path(root) / item['local_path']
                if not path.is_file():
                    result['absent'].append(item['local_path'])
                elif hashlib.sha256(path.read_bytes()).hexdigest() != item['sha256']:
                    result['mismatch'].append(item['local_path'])
                else:
                    result['ok'] += 1
    return result


# --- generated own-brand model-prefix alias list -------------------------------------------

def devices_digest(db):
    rows = [list(r) for r in db.execute('SELECT id,brand,model,kind FROM devices ORDER BY id')]
    return hashlib.sha256(json.dumps(rows, ensure_ascii=False).encode()).hexdigest(), len(rows)


def generate_alias_pairs(db, all_kinds=False):
    """Groups of same-brand identities whose models differ only by a leading own-brand token."""
    groups = {}
    for r in db.execute('SELECT id,brand,model,kind FROM devices ORDER BY brand,model,id'):
        if not all_kinds and kind_excluded(r['kind']):
            continue
        skey, stripped = stripped_key(r['brand'], r['model'])
        if skey:
            groups.setdefault((normalize(r['brand']), skey), []).append((r, stripped))
    out = []
    for (brand_norm, skey), items in groups.items():
        if not any(s for _, s in items) or len({plain_key(r['model']) for r, _ in items}) < 2:
            continue
        out.append({'brand_normalised': brand_norm, 'alias_key': skey,
                    'members': [{'id': r['id'], 'brand': r['brand'], 'model': r['model'], 'brand_token_stripped': s}
                                for r, s in sorted(items, key=lambda x: (x[0]['brand'], x[0]['model'], x[0]['id']))]})
    out.sort(key=lambda g: (g['brand_normalised'], g['alias_key']))
    return out


def alias_section(db, generated_on=None):
    digest, count = devices_digest(db)
    pairs = generate_alias_pairs(db)
    return {'rule': RULE, 'generated_on': generated_on or dt.date.today().isoformat(),
            'generated_from': {'devices_digest_sha256': digest, 'devices': count,
                               'note': 'sha256 of the ordered (id,brand,model,kind) rows; audit only. '
                                       'The stored list may go stale as the catalog grows; the code rule is authoritative.'},
            'generated_by': 'python3 -m devicehunt.brand_families regenerate-aliases --write',
            'groups': len(pairs), 'pairs': pairs}


def _connect(path):
    db = sqlite3.connect(Path(path).resolve().as_uri() + '?mode=ro', uri=True)
    db.row_factory = sqlite3.Row
    return db


def main(argv=None):
    parser = argparse.ArgumentParser(prog='python3 -m devicehunt.brand_families')
    parser.add_argument('command', choices=['check', 'regenerate-aliases'])
    parser.add_argument('--file', type=Path, default=DEFAULT_PATH)
    parser.add_argument('--db', type=Path, default=ROOT / 'data/devices.sqlite')
    parser.add_argument('--write', action='store_true', help='regenerate-aliases: rewrite model_prefix_aliases in --file')
    args = parser.parse_args(argv)
    table = load(args.file)
    db = _connect(args.db)
    try:
        if args.command == 'check':
            report = {'file': table.metadata(), 'catalog': check_catalog(table, db), 'evidence': verify_evidence(table)}
            stored = table.data.get('model_prefix_aliases', {})
            fresh = alias_section(db, stored.get('generated_on'))
            report['alias_list_current'] = stored.get('pairs') == fresh['pairs']
            print(json.dumps(report, ensure_ascii=False, indent=2))
            return 1 if report['catalog']['missing'] or report['evidence']['mismatch'] else 0
        section = alias_section(db)
    finally:
        db.close()
    if not args.write:
        print(json.dumps(section, ensure_ascii=False, indent=2))
        return 0
    data = dict(table.data, model_prefix_aliases=section)
    args.file.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
