import copy
import json
import tempfile
import unittest
from pathlib import Path

from devicehunt import ocnos, specifications
from devicehunt.catalog import Catalog, digest


def platform(model='AS5915-18X', vendor='Edgecore'):
    return {'id': model, 'vendor': vendor, 'commercialName': 'CSR200' if vendor == 'Edgecore' else '',
            'nos': 'SP', 'asicFull': 'Qumran UX (BCM88272)', 'ocnosVer': 'OcNOS 7.0.1',
            'form': '1RU', 'dimMm': '440 × 240 × 44 mm', 'dimIn': '17 × 9 × 1.7 in',
            'weight': '~4.2 kg', 'ram': '1 GB', 'opTemp': '-10°C–55°C', 'power': '~60 W',
            'special': '', 'status': 'active', 'datasheet': '', 'cap': 64,
            'ports': {k: (6 if k == 'g10' else 0) for k in ocnos.PORTS},
            'skus': ['OcNOS-SP-IPBASE-64'], 'firmware': ['ONIE Version: 2020.05', 'ONIE Version: 2020.05'],
            'roles': ['csr'], 'flags': {'fanless': False},
            'lifecycle': {'announce': '2026-09-08', 'eos': '2027-02-28', 'eol': '2030-08-28'}}


def html(rows):
    # Independent literal column fixture, not generated by the importer.
    body = '<link rel="canonical" href="' + ocnos.URL + '"><section><h2>OcNOS validated hardware platforms (' + str(len(rows)) + ')</h2><table>'
    body += '<tr>' + ''.join('<th>' + h + '</th>' for h in ocnos.HEADERS) + '</tr>'
    for p in rows:
        title = p['id'] + (' (' + p['commercialName'] + ')' if p['commercialName'] else '')
        body += '<tr>' + ''.join('<td>' + v + '</td>' for v in [title, 'OcNOS-SP', p['vendor'],
            'Qumran UX (BCM88272)', '64 Gbps', 'OcNOS 7.0.1', '1RU', '6x10G', 'roles: csr']) + '</tr>'
    return body + '</table></section>'


class OcNOSTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.c = Catalog(self.root / 'db.sqlite')

    def tearDown(self):
        self.c.db.close()
        self.tmp.cleanup()

    def bundle(self, rows=None, table=None):
        rows = rows if rows is not None else [platform(), platform('S9501-18SMT', 'UfiSpace')]
        hp = self.root / 'hcl.html'; hp.write_text(html(rows) if table is None else table)
        jp = self.root / 'platforms.json'; jp.write_text(json.dumps(rows))
        def ref(p): return {'path': p.name, 'sha256': digest(p.read_bytes())}
        bp = self.root / 'bundle.json'
        bp.write_text(json.dumps({'schema_version': 1, 'url': ocnos.URL, 'api_url': ocnos.API,
                                 'html': ref(hp), 'api': ref(jp)}))
        return bp

    def test_scoped_specs_alias_lifecycle_and_reimport(self):
        path = self.bundle()
        for _ in range(2):
            self.assertEqual(ocnos.import_bundle(self.c, path), {'platforms': 2, 'imported': 1})
        self.assertEqual(len(self.c.search('CSR200')), 1)
        self.assertEqual(self.c.search(role='manufacturer'), [])
        self.assertEqual(self.c.search(hyperscaler=True), [])
        self.assertEqual(self.c.db.execute('SELECT count(*) FROM records').fetchone()[0], 1)
        facts = [tuple(r) for r in self.c.db.execute('SELECT name,value FROM facts')]
        self.assertIn(('ocnos_hardware_end_of_sale', '2027-02-28'), facts)
        self.assertEqual(sum(k == 'compatibility_firmware_context' for k, v in facts), 1)
        self.assertFalse(any(k in ('manufacturer', 'lifecycle_status', 'max_speed') for k, v in facts))
        power = [r['statement'] for r in specifications.search(self.c, 'CSR200', exact_model=True)
                 if r['category'] == 'power_description']
        self.assertIn('~60 W', power[0])
        self.assertIn('unspecified', power[0])

    def test_mismatched_sources_truncation_and_duplicate_identity_rejected(self):
        rows = [platform(), platform('DS1000', 'Celestica')]
        good = html(rows)
        for change in [lambda r: r.pop(), lambda r: r[0].update(asicFull='Different ASIC'),
                       lambda r: r[0].update(ocnosVer='OcNOS 6.0'),
                       lambda r: r[0]['ports'].update(g10=4),
                       lambda r: r[0].update(cap=120), lambda r: r[1].update(id=r[0]['id']),
                       lambda r: r[0].update(commercialName='Other'),
                       lambda r: r[0]['lifecycle'].update(eos='2027-02-30'),
                       lambda r: r[0]['flags'].update(fanless='false')]:
            bad = copy.deepcopy(rows); change(bad)
            with self.assertRaises(ValueError): ocnos.parse(good, bad)
        with self.assertRaises(ValueError): ocnos.parse(good.replace('ASIC', 'Chip'), rows)

    def test_failed_refresh_preserves_existing_records_and_checks_dependencies(self):
        path = self.bundle(); ocnos.import_bundle(self.c, path)
        before = [tuple(r) for r in self.c.db.execute('SELECT * FROM records')]
        (self.root / 'platforms.json').write_text('[]')
        with self.assertRaisesRegex(ValueError, 'checksum'): ocnos.import_bundle(self.c, path)
        path = self.bundle([platform()], html([platform()]).replace('64 Gbps', '32 Gbps'))
        with self.assertRaisesRegex(ValueError, 'capacity'): ocnos.import_bundle(self.c, path)
        self.assertEqual(before, [tuple(r) for r in self.c.db.execute('SELECT * FROM records')])
        b = json.loads(path.read_text()); b['html']['path'] = '../outside.html'; path.write_text(json.dumps(b))
        with self.assertRaises(ValueError): ocnos.import_bundle(self.c, path)

    def test_empty_lifecycle_does_not_become_active_support_claim(self):
        p = platform('DS1000', 'Celestica'); p['lifecycle'] = []
        ocnos.import_bundle(self.c, self.bundle([p]))
        self.assertEqual(self.c.db.execute("SELECT count(*) FROM facts WHERE name LIKE 'ocnos_hardware_%'").fetchone()[0], 0)
        self.assertEqual(self.c.db.execute("SELECT count(*) FROM facts WHERE name='cooling_description'").fetchone()[0], 0)
