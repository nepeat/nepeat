//! --read --page): cage 1 Molex 1064281405 400G-DR4 (CMIS 4.0, paged), cage 3 TE
//! 2459398-1 passive DAC (CMIS 4.0, flat). Serial numbers are the modules' own.

fn hex(lines: &[&str]) -> Vec<u8> {
    lines
        .concat()
        .split_whitespace()
        .filter_map(|b| u8::from_str_radix(b, 16).ok())
        .collect()
}

