/// The first entry of that name (`lookup`).
pub fn lookup(t: &[Name], s: &str) -> Option<i64> {
    t.iter().find(|(n, _)| *n == s).map(|(_, v)| *v)
}

/// The last entry of that name (`make_attr`'s table loop).
pub fn lookup_last(t: &[Name], s: &str) -> Option<i64> {
    t.iter().rev().find(|(n, _)| *n == s).map(|(_, v)| *v)
}

