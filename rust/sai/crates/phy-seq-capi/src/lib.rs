//! The C interface of [`phy_seq`]: `include/phy_seq.h` and the static library
//! `libphy_seq_capi.a`, for the C++ libsai (sai-openbcm built with `RUST_PHY_SEQ=...`), which
//! keeps its own structs and has its parser and executor implemented by calls into this crate.
//!
//! # Shape
//!
//! * [`sys`]: the declarations bindgen makes from the header at build time. The structs the
//!   functions take are those; nothing is declared twice by hand.
//! * `flat`, `table` (no unsafe): [`phy_seq::Op`] to and from the header's `phy_seq_op`. An
//!   operation that comes in from C is checked field by field and becomes a typed operation or
//!   an error; what the executor runs is always the checked type.
//! * `ptr`: four small unsafe helpers (slice in, reference in, value out, text out).
//! * `api`: the seven exported functions. Each runs inside `catch_unwind`: a panic becomes
//!   `PHY_SEQ_E_PANIC` and never crosses into C. (That needs `panic = "unwind"`, which the
//!   workspace profiles set; with `abort` a panic ends the process, still without undefined
//!   behaviour.)
//!
//! # Unsafe inventory
//!
//! This is the only crate of the pair with unsafe code, and inside it only `ptr` and `api` may
//! have any (`#![deny(unsafe_code)]` at the root, allowed in those two modules). No `static mut`,
//! no `unsafe impl`, no global state at all: a table is a heap object owned by the C caller.
//! Every unsafe block does one thing and says why it is sound; the contract a C caller must
//! keep is written in the header and repeated at the functions.
//!
//! # Key material
//!
//! `phy_seq_exec` copies the parameter bytes into a [`phy_seq::Params`] (wiped on drop) and
//! reads them only to build bus words. No message this crate writes holds a parameter byte.
#![deny(unsafe_code)]

mod api;
mod flat;
mod ptr;
mod table;

/// The declarations of `include/phy_seq.h`, generated by bindgen at build time.
#[allow(
    non_camel_case_types,
    non_upper_case_globals,
    missing_docs,
    unreachable_pub,
    unsafe_code,
    clippy::all,
    clippy::pedantic,
    clippy::restriction,
    reason = "generated code: the header's names, and declarations of extern functions"
)]
pub mod sys {
    include!(concat!(env!("OUT_DIR"), "/phy_seq.rs"));
}

pub use api::{
    phy_seq_abi, phy_seq_exec, phy_seq_free, phy_seq_parse, phy_seq_table_info, phy_seq_table_port, phy_seq_table_seq,
};
