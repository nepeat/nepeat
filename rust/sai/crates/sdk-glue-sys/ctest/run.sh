#!/usr/bin/env bash
# Unit test for the argument range checks (OB_CHECK_UNIT/_BCM/_PORT/_VID/_PARAM/_MDIO) at the top
# of the 27 checked functions in ai_re/nix/packages/sai-openbcm/src/sdk_glue.c: out-of-range
# units, ports, VLAN ids, modes, ids and MDIO addresses, and calls before bring-up, must be
# refused with the right code before any SDK call; valid arguments must reach the SDK.
# check_args.c includes sdk_glue.c; every SDK function is a logging stub (stubs.c, generated
# below from nm -u), so nothing here talks to a switch.
#
# Needs the big-endian ppc64 OpenBCM libsdk *headers* (libsdk itself is not linked), the
# powerpc64 cross gcc, and qemu-ppc64. Not part of the cargo test suite: run it by hand.
#   ./run.sh [build-dir]          (default: a fresh dir under $TMPDIR)
# Override the tools with SDK=, CROSS_GCC=, QEMU_PPC64=.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
glue_src=${GLUE_SRC:-$(cd "$here/../../../../../ai_re/nix/packages/sai-openbcm/src" && pwd)}   # GLUE_SRC: e.g. a mutated copy
SDK=${SDK:-/nix/store/2g5lynabfnvfdz8y8vr6vjg2189y0sj4-openbcm-libsdk-powerpc64-unknown-linux-gnuabielfv2-6.5.27}
CROSS_GCC=${CROSS_GCC:-/nix/store/higvw1d5adlys0hzy8aclvzhy5psawr3-powerpc64-unknown-linux-gnuabielfv2-gcc-wrapper-16.2.0/bin/powerpc64-unknown-linux-gnuabielfv2-gcc}
QEMU_PPC64=${QEMU_PPC64:-/nix/store/037j0xk9zyspzrd5s7y3k846qhjxvi0v-qemu-11.1.0/bin/qemu-ppc64}
NM=${CROSS_GCC%gcc}nm

for f in "$SDK/share/openbcm/cflags" "$CROSS_GCC" "$NM" "$QEMU_PPC64"; do
    [ -e "$f" ] || { echo "missing: $f" >&2; exit 2; }
done

out=${1:-$(mktemp -d "${TMPDIR:-/tmp}/sdk-glue-ctest.XXXXXX")}
mkdir -p "$out"

# The flags sdk_glue.c is built with.
# shellcheck disable=SC2046
cflags=(-std=gnu11 -fPIC -Wall -Wno-unused-function -O2 -g $(cat "$SDK/share/openbcm/cflags")
        -I"$SDK/include/openbcm/include" -I"$SDK/include/openbcm/bde" -I"$SDK/include/openbcm/kmod"
        -I"$SDK/include/openbcm/phymod" -I"$glue_src")

"$CROSS_GCC" "${cflags[@]}" -Werror -c "$here/check_args.c" -o "$out/check_args.o"

# One stub per symbol the test object still needs that libc does not define. Every stub
# logs its name and returns 0 (= BCM_E_NONE; NULL for pointers). No prototypes: this file
# includes no SDK header, and on ELFv2 an int/void/pointer result in r3 is all a caller reads.
libc=$("$CROSS_GCC" -print-file-name=libc.so.6)
"$NM" -D --defined-only "$libc" | awk '{print $NF}' | sed 's/@.*//' | sort -u > "$out/libc.syms"
"$NM" -u "$out/check_args.o" | awk '{print $NF}' | grep -v '^\.TOC\.$' | sort -u > "$out/undef.syms"
comm -23 "$out/undef.syms" "$out/libc.syms" > "$out/stub.syms"
{
    echo "/* generated by run.sh from nm -u check_args.o: SDK stubs */"
    echo "void ob_stub_called(const char* name);"
    while read -r s; do
        echo "long $s(void) { ob_stub_called(\"$s\"); return 0; }"
    done < "$out/stub.syms"
} > "$out/stubs.c"
"$CROSS_GCC" -std=gnu11 -fPIC -O2 -w -c "$out/stubs.c" -o "$out/stubs.o"
"$CROSS_GCC" -o "$out/check_args" "$out/check_args.o" "$out/stubs.o"
echo "built $out/check_args ($(wc -l < "$out/stub.syms") SDK stubs)"

glibc=$(dirname "$(dirname "$libc")")
"$QEMU_PPC64" -L "$glibc" "$out/check_args"
