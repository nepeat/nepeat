use std::fmt::Write as _;

const CONFIG_BCM: &str = include_str!("as7760/config.bcm.txt");
const PORT_CONFIG: &str = include_str!("as7760/port_config.ini.txt");
const RC: &str = include_str!("as7760/led_proc_init.soc.txt");

/// A port of `SONiC`'s `port_config.ini`.
#[derive(Debug, Clone, PartialEq, Eq)]
struct SonicPort {
    name: String,
    lanes: Vec<u32>,
    speed: u32,
}

fn sonic_ports() -> Vec<SonicPort> {
    PORT_CONFIG
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .map(|l| {
            let w: Vec<&str> = l.split_whitespace().collect();
            SonicPort {
                name: w[0].to_owned(),
                lanes: w[1].split(',').map(|x| x.parse().unwrap()).collect(),
                speed: w[4].parse().unwrap(),
            }
        })
        .collect()
}

/// `(logical, first physical lane, Gb/s)` of every `portmap_` line.
fn portmap() -> Vec<(u32, u32, u32)> {
    CONFIG_BCM
        .lines()
        .filter_map(|l| l.trim().strip_prefix("portmap_"))
        .map(|rest| {
            let (logical, value) = rest.split_once('=').unwrap();
            let (phys, speed) = value.split_once(':').unwrap();
            (logical.parse().unwrap(), phys.parse().unwrap(), speed.parse().unwrap())
        })
        .collect()
}

/// The front-panel ports as the glue reports them: `port <logical> <phys> <lanes> <Mb/s> <name>`
/// lines (the Rust fake's directive and the virtual backend's port map), logical order.
fn sdk_port_lines() -> String {
    let mut ports: Vec<(u32, u32, u32)> = portmap().into_iter().filter(|(_, phys, _)| *phys <= 128).collect();
    ports.sort_unstable();
    let (mut ce, mut xe) = (0, 0);
    let mut out = String::new();
    for (logical, phys, gbps) in ports {
        let lanes = match gbps {
            100 | 40 => 4,
            50 => 2,
            25 | 10 => 1,
            other => panic!("no Tomahawk lane count for {other}G"),
        };
        let name = if lanes == 1 {
            xe += 1;
            format!("xe{}", xe - 1)
        } else {
            ce += 1;
            format!("ce{}", ce - 1)
        };
        let _ = writeln!(out, "port {logical} {phys} {lanes} {} {name}", gbps * 1000);
    }
    out
}

/// `(logical, lanes, speed)` of every front-panel port of a switch, in `PORT_LIST` order.
fn sai_ports<B: Backend>(sai: &Sai<B>, switch: RawOid) -> Vec<(u16, Vec<u32>, u32)> {
    let Value::OidList(list) = sai
        .get(sys::SAI_OBJECT_TYPE_SWITCH, switch, &[sys::SAI_SWITCH_ATTR_PORT_LIST])
        .unwrap()
        .remove(0)
    else {
        panic!("PORT_LIST")
    };
    list.into_iter()
        .map(|p| {
            let v = sai
                .get(
                    sys::SAI_OBJECT_TYPE_PORT,
                    p,
                    &[sys::SAI_PORT_ATTR_HW_LANE_LIST, sys::SAI_PORT_ATTR_SPEED],
                )
                .unwrap();
            let (Value::U32List(lanes), Value::U32(speed)) = (&v[0], &v[1]) else {
                panic!("{v:?}")
            };
            // the port id carries the logical port (C++ make_oid(PORT, hw))
            (u16::try_from(p.0 & 0xffff).unwrap(), lanes.clone(), *speed)
        })
        .collect()
}

/// Every `SONiC` port is exactly one SAI port with its lanes and speed, and nothing else is.
#[track_caller]
fn matches_sonic(ports: &[(u16, Vec<u32>, u32)]) {
    let sonic = sonic_ports();
    assert_eq!(ports.len(), sonic.len(), "{ports:?}");
    for s in &sonic {
        let found: Vec<_> = ports.iter().filter(|(_, lanes, _)| *lanes == s.lanes).collect();
        assert_eq!(found.len(), 1, "{}: lanes {:?} in {ports:?}", s.name, s.lanes);
        assert_eq!(found[0].2, s.speed, "{}: speed", s.name);
    }
    // the SDK's order: ascending logical ports
    let logical: Vec<u16> = ports.iter().map(|p| p.0).collect();
    let mut sorted = logical.clone();
    sorted.sort_unstable();
    assert_eq!(logical, sorted);
}

#[test]
fn the_fixtures_are_the_as7760_files() {
    let map = portmap();
    assert_eq!(map.len(), 40); // 38 front-panel + 2 management
    assert_eq!(sonic_ports().len(), 38);
    let breakout: Vec<_> = map.iter().filter(|(_, _, g)| *g == 25).map(|(l, _, _)| *l).collect();
    assert_eq!(breakout, [50, 51, 52, 53, 13, 14, 15, 16]);
    assert_eq!(
        CONFIG_BCM
            .lines()
            .filter(|l| l.starts_with("serdes_preemphasis_"))
            .count(),
        128
    );
    // the rc file: the LED processors' port-order remap and program
    assert_eq!(RC.lines().filter(|l| l.contains("_PORT_ORDER_REMAP_")).count(), 32);
    assert!(RC.lines().any(|l| l.starts_with("led ")), "an LED program");
    let lines = sdk_port_lines();
    assert_eq!(lines.lines().count(), 38);
    assert_eq!(parse_port_map(&lines).unwrap().len(), 38);
}

#[test]
fn the_virtual_backend_lays_the_as7760_ports_out_from_a_port_map() {
    let path = unique("as7760.ports");
    std::fs::write(&path, sdk_port_lines()).unwrap();
    let profile = Profile::from_pairs([("SAI_RS_VIRTUAL_PORT_MAP", path.display().to_string())]);
    let mut sai = Sai::new(VirtualBackend::new());
    let switch = sai
        .create_switch(
            &[Attr::new(sys::SAI_SWITCH_ATTR_INIT_SWITCH, Value::Bool(true))],
            &profile,
        )
        .unwrap()
        .raw();
    let ports = sai_ports(&sai, switch);
    matches_sonic(&ports);
    // the first break-out port: logical 50, one lane (physical 49), 25G
    let first = ports.iter().find(|p| p.0 == 50).unwrap();
    assert_eq!((first.1.as_slice(), first.2), (&[49][..], 25_000));
}

#[test]
fn the_openbcm_backend_reports_the_as7760_ports_the_sdk_lays_out() {
    let dir = unique("as7760");
    std::fs::create_dir_all(&dir).unwrap();
    let scenario = dir.join("scenario.cfg");
    std::fs::write(&scenario, format!("knet 38 38\n{}", sdk_port_lines())).unwrap();
    let rc = dir.join("led_proc_init.soc");
    std::fs::write(&rc, RC).unwrap();
    let chip = Chip::new();
    chip.record(true);
    let profile = Profile::from_pairs([
        ("SAI_INIT_CONFIG_FILE", scenario.display().to_string()),
        ("SAI_OPENBCM_RC_FILE", rc.display().to_string()),
    ]);
    let mut sai = Sai::new(OpenbcmBackend::on_chip(chip.clone()));
    let switch = sai
        .create_switch(
            &[Attr::new(sys::SAI_SWITCH_ATTR_INIT_SWITCH, Value::Bool(true))],
            &profile,
        )
        .unwrap()
        .raw();
    matches_sonic(&sai_ports(&sai, switch));
    // The glue is given the profile's two files as they are: the C++ backend's
    // ob_sdk_init(unit_, config.c_str(), rc.c_str(), err, sizeof(err)) with a 256-byte buffer.
    let record = chip.take_record();
    let init = record.iter().find(|l| l.starts_with("init(")).unwrap();
    assert!(
        init.starts_with(&format!(
            "init(unit=0, config=\"{}\", rc=\"{}\", errlen=256) -> 0 ",
            scenario.display(),
            rc.display()
        )),
        "{init}"
    );
    assert_eq!(record.iter().filter(|l| l.starts_with("init(")).count(), 1);
}

#[test]
fn without_an_rc_file_the_glue_gets_an_empty_string_as_from_the_cpp() {
    let scenario = unique("as7760-no-rc.cfg");
    std::fs::write(&scenario, sdk_port_lines()).unwrap();
    for rc in [None, Some("")] {
        let chip = Chip::new();
        chip.record(true);
        let mut pairs = vec![("SAI_INIT_CONFIG_FILE".to_owned(), scenario.display().to_string())];
        if let Some(rc) = rc {
            pairs.push(("SAI_OPENBCM_RC_FILE".to_owned(), rc.to_owned()));
        }
        let mut backend = OpenbcmBackend::on_chip(chip.clone());
        let (sink, _events) = sai_core::backend::EventSink::channel();
        backend.init(&Profile::from_pairs(pairs), sink).unwrap();
        let record = chip.take_record();
        let init = record.iter().find(|l| l.starts_with("init(")).unwrap();
        assert!(
            init.starts_with(&format!(
                "init(unit=0, config=\"{}\", rc=\"\", errlen=256) -> 0 ",
                scenario.display()
            )),
            "{init}"
        );
        backend.shutdown();
    }
}
