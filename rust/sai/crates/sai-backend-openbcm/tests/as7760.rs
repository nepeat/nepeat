//! The Edge-Core AS7760-32X's port layout (25G break-out next to 100G ports), never run on its
//! chip by this library: the ports come from the backend (no `create_port`; the C++ frontend's
//! `switch_build_objects` takes `ob_sdk_ports` as it comes, as the Rust one does), so what has to
//! hold is that a mixed layout from the SDK reaches SAI as `SONiC`'s port config for the board
//! expects it: one port per `SONiC` port, its lanes, its speed, in the SDK's (logical) order.
//!
//! Fixtures (`tests/as7760/*.txt`: `.txt` so the package's source filter takes them; copied unchanged from the AS7760 system at commit 50a6aa7, the same
//! store paths for implementation `cpp` and `rust`): `config.bcm` =
//! `/nix/store/0aswqlrkwphayh2cbrhx5zgi6k9np8df-as7760-32x-config.bcm` (sha256 `ae0c97ad…`,
//! generated by `ai_re/nix/packages/openbcm/configs/tomahawk.py` from the board module
//! `ai_re/nix/modules/boards/as7760`; the pin of `sdk-config-test.nix`), `port_config.ini` =
//! `…-port_config.ini` (`2a631457…`), `led_proc_init.soc` = the rc file
//! `SAI_OPENBCM_RC_FILE` (`3f6fda1d…`, LED program + port-order remap). The generator's inputs
//! are Nix expressions plus a file of the pinned sonic-buildimage source, so the generated files
//! are copied, not derived here: a change of the board's layout shows as a differing hash.
//!
//! What the SDK makes of `portmap_<logical>=<first physical lane>:<Gb/s>` is modelled here as the
//! glue reports it (`ob_sdk_ports`: logical ports in ascending order, `phys` the first lane,
//! lanes by speed on the Tomahawk: 100G and 40G four, 50G two, 25G and 10G one; management ports,
//! physical 129..=132, left out by the glue): the Rust fake's `port` directives and the virtual
//! backend's port map are made from it. The SDK's port names are not modelled (`ce` / `xe` +
//! a count here); `SONiC` maps ports by lanes.
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    clippy::too_many_lines
)]
mod common;

